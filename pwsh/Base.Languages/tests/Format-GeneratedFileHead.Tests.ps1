Describe 'Format-GeneratedFileHead' -Tag 'L0', 'logic', 'ADR-REPO-FILEMETA-COMPOSEDFILES' {
    BeforeAll {
        $script:languages = [Catzc.Base.Languages.LanguagesConfig]::new(@{
                languages = [ordered]@{
                    widget = @{ extensions = @('.wdg'); no_formatter = 'widgets are never formatted' }
                    gadget = @{ extensions = @('.gdg'); no_formatter = 'gadgets are never formatted' }
                    stamp  = @{ extensions = @('.stp'); no_formatter = 'a stamp is written whole' }
                    data   = @{ extensions = @('.dat'); no_formatter = 'data is never formatted' }
                }
            })
        $script:carriers = [Catzc.Base.Languages.FileCarriersConfig]::new(@{
                carriers = [ordered]@{
                    widget   = @{ carrier = 'comment-head'; line = '#' }
                    gadget   = @{ carrier = 'comment-head'; block = @('/*', '*/') }
                    stamp    = @{ carrier = 'none'; reason = 'written whole' }
                    data     = @{ carrier = 'property'; property = '//' }
                    sprocket = @{ files = @('**/sprocket'); carrier = 'comment-head'; line = '//' }
                    schema   = @{ files = @('**/*.schema.dat'); carrier = 'property'; property = '$comment'; strip = @((Get-Config -Config generated-head).warning) }
                    cog      = @{ files = @('**/cog.mod'); carrier = 'banner'; banner = '// Code generated by widget. DO NOT EDIT.' }
                    picture  = @{ files = @('**/*.pic'); carrier = 'png-text' }
                    drawing  = @{ files = @('**/*.drw'); carrier = 'metadata' }
                    markup   = @{ files = @('**/*.mkp'); carrier = 'processing-instruction' }
                }
            })
        $script:warning = (Get-Config -Config generated-head).warning
        $script:arguments = @{ Carriers = $script:carriers; Languages = $script:languages }
        $script:writer = [Catzc.Base.Variants.GeneratedWriterRow]::new('Build-Widget', [ordered]@{
                class   = 'rollable'
                inputs  = @('docs/widget/*.yml', 'docs/gadget.yml')
                outputs = @('docs/gen.wdg', [ordered]@{ path = 'docs/**/*.pic'; inputs = @('docs/pic/*.yml') })
            })
        $script:gadget = [Catzc.Base.Variants.GeneratedWriterRow]::new('Build-Gadget', [ordered]@{
                class      = 'rollable'
                inputs     = @('docs/widget/*.yml')
                outputs    = @([ordered]@{ path = 'docs/**/*.wdg'; inputs = @('docs/z.yml', 'docs/a.yml') })
                regenerate = 'Build-Gadget -All'
            })
        # The smallest png: its signature, a 1x1 IHDR and an IEND, each chunk closed by its CRC.
        $script:chunk = {
            param([string] $Type, [byte[]] $Data)
            $body = [byte[]] @([System.Text.Encoding]::ASCII.GetBytes($Type) + $Data)
            $crc = [Catzc.Base.Languages.PngTextCarrier]::Crc($body, 0, $body.Length)
            [byte[]] @([System.BitConverter]::GetBytes([uint32] $Data.Length)[3..0] + $body + [System.BitConverter]::GetBytes([uint32] $crc)[3..0])
        }
        $script:png = [byte[]] @(
            [byte[]] @(0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A)
            (& $script:chunk 'IHDR' ([byte[]] @(0, 0, 0, 1, 0, 0, 0, 1, 8, 0, 0, 0, 0)))
            (& $script:chunk 'IEND' ([byte[]] @()))
        )
    }

    BeforeEach {
        # A fixture for whether git tracks the path, which the index read answers in production.
        $script:tracked = $true
        Mock Get-GitTrackedPath -ModuleName Catzc.Base.Languages { if ($script:tracked) {
                $Path
            } }
        # The writer registry, which every module's generated.yml answers in production.
        Mock Get-GeneratedWriterRow -ModuleName Catzc.Base.Languages { @($script:writer, $script:gadget) | Where-Object name -CEQ $Name }
    }

    It 'writes the one declared warning into every head, whatever the carrier' {
        $heads = @(
            Format-GeneratedFileHead -Text "body`n" -Path 'docs/gen.wdg' -Carriers $script:carriers -Languages $script:languages
            Format-GeneratedFileHead -Text "body`n" -Path 'docs/gen.gdg' -Carriers $script:carriers -Languages $script:languages
            Format-GeneratedFileHead -Text "body`n" -Path 'sprocket' -Carrier sprocket -Carriers $script:carriers -Languages $script:languages
            Format-GeneratedFileHead -Text "{`n  `"a`": 1`n}`n" -Path 'docs/gen.dat' -Carriers $script:carriers -Languages $script:languages
        )
        foreach ($head in $heads) {
            $head | Should -BeLike "*warning: *$script:warning*"
        }
        $script:warning | Should -BeExactly ([Catzc.Base.Languages.GeneratedHeadConfig]::DefaultWarning)
    }

    It 'writes the body hash of a tracked file and the warning, and nothing else, in the comment style of the file language' {
        $text = Format-GeneratedFileHead -Text "widget body`n" -Path 'docs/gen.wdg' -Carriers $script:carriers -Languages $script:languages
        $text |
            Should -BeExactly "# ---`n# catzc:`n#   immutable:`n#     warning: `"$script:warning`"`n#     with_body_sha: `"9534a2e15c8b`"`n# ---`n`nwidget body`n"
        Should -Invoke Get-GitTrackedPath -ModuleName Catzc.Base.Languages -Times 1 -ParameterFilter { $Path -contains 'docs/gen.wdg' }
    }

    It 'opens the immutable part with the warning and closes it with the body hash, whatever the carrier' -Tag 'ADR-REPO-FILEMETA-COMPOSEDFILES' {
        foreach ($path in 'docs/gen.wdg', 'docs/gen.gdg') {
            $text = Format-GeneratedFileHead -Text "body`n" -Path $path -Carriers $script:carriers -Languages $script:languages
            $text |
                Should -Match '(?m)^\W*immutable:\r?\n\W*warning: ' -Because "the first key under immutable in $path is the warning"
            $text |
                Should -Match '(?m)^\W*with_body_sha: "?[0-9a-f]{12}"?\r?\n\W*---' -Because "the last key under immutable in $path is the body hash"
        }
    }

    It 'writes the warning only on a file git does not track' {
        $script:tracked = $false
        $text = Format-GeneratedFileHead -Text "widget body`n" -Path 'docs/gen.wdg' -Carriers $script:carriers -Languages $script:languages
        $text |
            Should -BeExactly "# ---`n# catzc:`n#   immutable:`n#     warning: `"$script:warning`"`n# ---`n`nwidget body`n"
    }

    It 'writes no place fact, no generator, no source and no edge: each is derived on demand' {
        $text = Format-GeneratedFileHead -Text "body`n" -Path "$(Get-CatzcModulesFolder)/Catzc.Base.Docs/gen.wdg" -Carriers $script:carriers -Languages $script:languages
        foreach ($key in 'role', 'track', 'generator', 'source', 'with_inputs_sha', 'docs', 'edges') {
            $text | Should -Not -BeLike "*#     ${key}:*"
            $text | Should -Not -BeLike "*#   ${key}:*"
        }
        foreach ($parameter in 'Generator', 'Source', 'FileKind', 'Pages', 'InputsSha') {
            (Get-Command Format-GeneratedFileHead).Parameters.Keys | Should -Not -Contain $parameter
        }
    }

    It 'hashes the body only, which the head itself and the line endings never move' {
        $arguments = @{ Path = 'docs/gen.wdg' } + $script:arguments
        $once = Format-GeneratedFileHead -Text "body`n" @arguments
        # A hash that opens with a digit is quoted, or YAML would not read it back as the same string.
        $once | Should -BeLike "*#     with_body_sha: `"9e2ec912af5d`"`n*"
        Format-GeneratedFileHead -Text $once @arguments | Should -BeLike '*with_body_sha: "9e2ec912af5d"*'
        Format-GeneratedFileHead -Text "body`r`n" @arguments | Should -BeLike '*with_body_sha: "9e2ec912af5d"*'
        Format-GeneratedFileHead -Text "other`n" @arguments | Should -Not -BeLike '*with_body_sha: "9e2ec912af5d"*'
    }

    It 'is stable: a second run over its own output changes nothing, tracked or not' -ForEach @(@{ Exit = 0 }, @{ Exit = 1 }) {
        $script:tracked = $Exit -eq 0
        $arguments = @{ Path = 'docs/gen.gdg' } + $script:arguments
        $once = Format-GeneratedFileHead -Text "body`n" @arguments
        Format-GeneratedFileHead -Text $once @arguments | Should -BeExactly $once
    }

    It 'finds the carrier of a file with no language by its glob, a named carrier winning, and refuses a file no entry takes' {
        $text = Format-GeneratedFileHead -Text "body`n" -Path 'docs/sprocket' @script:arguments
        $text | Should -BeLike "// ---`n// catzc:*`n// ---`n`nbody`n"
        Format-GeneratedFileHead -Text "body`n" -Path 'docs/gen.wdg' -Carrier sprocket @script:arguments | Should -BeLike "// ---`n// catzc:*"
        { Format-GeneratedFileHead -Text 'body' -Path 'docs/gen.widget-unknown' @script:arguments } | Should -Throw '*matches no file-carriers.yml entry, by glob or by file language*'
    }

    It 'finds a carrier by its glob before the carrier of the file language' {
        $json = "{`n  `"type`": `"object`"`n}`n"
        Format-GeneratedFileHead -Text $json -Path 'docs/gen.schema.dat' @script:arguments | Should -BeLike "*`"`$comment`": `"catzc:*"
        Format-GeneratedFileHead -Text $json -Path 'docs/gen.dat' @script:arguments | Should -BeLike "*`"//`": `"catzc:*"
    }

    It 'writes a property carrier into JSON, replacing an old banner its carrier strips' {
        $json = "{`n  `"`$comment`": `"$script:warning`",`n  `"type`": `"object`"`n}`n"
        $bare = Format-PropertyMetaHead -Text $json -Property '$comment' -Strip @($script:warning) -Immutable ([ordered]@{})
        $hash = [Catzc.Base.MarkdownMeta.MarkdownDocument]::HashOf($bare)
        $text = Format-GeneratedFileHead -Text $json -Path 'docs/gen.schema.dat' -Carrier schema -Carriers $script:carriers -Languages $script:languages
        $text |
            Should -BeExactly "{`n  `"`$comment`": `"catzc:\n  immutable:\n    warning: \`"$script:warning\`"\n    with_body_sha: \`"$hash\`"`",`n  `"type`": `"object`"`n}`n"
    }

    It 'writes a banner carrier as its one line above the body, with no meta block, and a second run changes nothing' {
        $script:tracked = $false
        $arguments = @{ Path = 'cog.mod'; Carrier = 'cog' } + $script:arguments
        $once = Format-GeneratedFileHead -Text "module widget`n" @arguments
        $once | Should -BeExactly "// Code generated by widget. DO NOT EDIT.`n`nmodule widget`n"
        ($once -split "`n")[0] | Should -Match '^// Code generated .* DO NOT EDIT\.$' -Because 'the Go tools read this one line'
        Format-GeneratedFileHead -Text $once @arguments | Should -BeExactly $once
    }

    It 'refuses a banner carrier on a tracked file, which would need a body hash' {
        { Format-GeneratedFileHead -Text "module widget`n" -Path 'cog.mod' -Carrier cog @script:arguments } | Should -Throw '*holds no body hash*'
    }

    It 'fills regenerate from the writer row, the body hash closing the head, and writes no sources and no remove command' -Tag 'ADR-REPO-FILEMETA-COMPOSEDFILES', 'ADR-REPO-FILEMETA-PROVENANCEINHEAD' {
        $text = Format-GeneratedFileHead -Text "widget body`n" -Path 'docs/gen.wdg' -Writer Build-Widget @script:arguments
        $text |
            Should -BeExactly "# ---`n# catzc:`n#   immutable:`n#     warning: `"$script:warning`"`n#     regenerate: `"Build-Widget -Path docs/gen.wdg`"`n#     with_body_sha: `"9534a2e15c8b`"`n# ---`n`nwidget body`n"
        Format-GeneratedFileHead -Text $text -Path 'docs/gen.wdg' -Writer Build-Widget @script:arguments | Should -BeExactly $text
        Should -Invoke Get-GeneratedWriterRow -ModuleName Catzc.Base.Languages -ParameterFilter { $Name -ceq 'Build-Widget' }
    }

    It 'takes the row''s own regenerate command where it overrides the template' {
        $text = Format-GeneratedFileHead -Text "body`n" -Path 'docs/sub/gen.wdg' -Writer Build-Gadget @script:arguments
        $text | Should -BeLike "*#     regenerate: `"Build-Gadget -All`"`n#     with_body_sha: *"
    }

    It 'writes no command and no source on an untracked file, and reads no writer row for it' {
        $script:tracked = $false
        $text = Format-GeneratedFileHead -Text "widget body`n" -Path 'docs/gen.wdg' -Writer Build-Widget @script:arguments
        $text | Should -BeExactly "# ---`n# catzc:`n#   immutable:`n#     warning: `"$script:warning`"`n# ---`n`nwidget body`n"
        Should -Invoke Get-GeneratedWriterRow -ModuleName Catzc.Base.Languages -Times 0 -Exactly
    }

    It 'stamps a png in a catzc tEXt chunk whose body hash is the image without it, and a re-stamp is identical' -Tag 'ADR-REPO-FILEMETA-EVERYFORMATCARRIES' {
        $arguments = @{ Path = 'docs/gen.pic'; Writer = 'Build-Widget' } + $script:arguments
        $once = Format-GeneratedFileHead -Bytes $script:png @arguments
        $hash = [Catzc.Base.Languages.PngTextCarrier]::HashOf($script:png)
        $text = [Catzc.Base.Languages.PngTextCarrier]::Text($once)
        $text | Should -BeLike "catzc:`n  immutable:`n    warning: `"$script:warning`"`n    regenerate: `"Build-Widget -Path docs/gen.pic`"`n    with_body_sha: `"$hash`""
        [Catzc.Base.Languages.PngTextCarrier]::Body($once) | Should -Be $script:png
        $twice = Format-GeneratedFileHead -Bytes $once @arguments
        [System.Linq.Enumerable]::SequenceEqual([byte[]] $twice, [byte[]] $once) | Should -BeTrue
        $once.Length | Should -BeGreaterThan $script:png.Length
        [Catzc.Base.Languages.PngTextCarrier]::Crc([System.Text.Encoding]::ASCII.GetBytes('IEND'), 0, 4) | Should -Be ([uint32] 2923585666)
        # A png number is big-endian, so its four bytes are read reversed.
        $length = [int] [System.BitConverter]::ToUInt32([byte[]] $once[36..33], 0)
        [System.Text.Encoding]::ASCII.GetString($once, 37, 4) | Should -BeExactly 'tEXt'
        $crc = [Catzc.Base.Languages.PngTextCarrier]::Crc($once, 37, 4 + $length)
        [System.BitConverter]::ToUInt32([byte[]] $once[(44 + $length)..(41 + $length)], 0) | Should -Be $crc
    }

    It 'stamps an svg in a metadata element under its root, and a re-stamp is identical' -Tag 'ADR-REPO-FILEMETA-EVERYFORMATCARRIES' {
        $svg = "<svg xmlns=`"http://www.w3.org/2000/svg`"><rect width=`"1`"/></svg>`n"
        $arguments = @{ Path = 'docs/gen.drw'; Carrier = 'drawing' } + $script:arguments
        $once = Format-GeneratedFileHead -Text $svg @arguments
        $hash = [Catzc.Base.MarkdownMeta.MarkdownDocument]::HashOf($svg)
        $once |
            Should -BeExactly "<svg xmlns=`"http://www.w3.org/2000/svg`"><metadata id=`"catzc`"><![CDATA[catzc:`n  immutable:`n    warning: `"$script:warning`"`n    with_body_sha: `"$hash`"]]></metadata><rect width=`"1`"/></svg>`n"
        Format-GeneratedFileHead -Text $once @arguments | Should -BeExactly $once
        [Catzc.Base.Languages.SvgMetadataCarrier]::Body($once) | Should -BeExactly $svg
    }

    It 'stamps an xml file in a catzc processing instruction below its declaration, and a re-stamp is identical' -Tag 'ADR-REPO-FILEMETA-EVERYFORMATCARRIES' {
        $xml = "<?xml version=`"1.0`"?>`n<widget/>`n"
        $arguments = @{ Path = 'docs/gen.mkp'; Carrier = 'markup' } + $script:arguments
        $once = Format-GeneratedFileHead -Text $xml @arguments
        $hash = [Catzc.Base.MarkdownMeta.MarkdownDocument]::HashOf($xml)
        $once |
            Should -BeExactly "<?xml version=`"1.0`"?>`n<?catzc`n  immutable:`n    warning: `"$script:warning`"`n    with_body_sha: `"$hash`"`n?>`n<widget/>`n"
        Format-GeneratedFileHead -Text $once @arguments | Should -BeExactly $once
        [Catzc.Base.Languages.XmlInstructionCarrier]::Body($once) | Should -BeExactly $xml
        Format-GeneratedFileHead -Text "<widget/>`n" @arguments | Should -BeLike "<?catzc`n*`n?>`n<widget/>`n"
    }

    It 'takes a png by -Bytes and every other carrier by -Text' {
        { Format-GeneratedFileHead -Text 'body' -Path 'docs/gen.pic' -Carrier picture @script:arguments } | Should -Throw '*takes its content by -Bytes*'
        { Format-GeneratedFileHead -Bytes $script:png -Path 'docs/gen.wdg' @script:arguments } | Should -Throw '*takes its content by -Text*'
    }

    It 'refuses a carrier that holds no head, and an undeclared carrier' {
        { Format-GeneratedFileHead -Text 'body' -Path 'docs/gen.stp' -Carriers $script:carriers -Languages $script:languages } | Should -Throw '*of kind None*'
        { Format-GeneratedFileHead -Text 'body' -Path 'docs/gen.wdg' -Carrier gizmo -Carriers $script:carriers -Languages $script:languages } | Should -Throw "*names the carrier 'gizmo'*"
    }
}
