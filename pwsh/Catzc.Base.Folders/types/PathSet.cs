using System;
using System.Collections.Generic;
using System.IO;

namespace Catzc.Base.Folders;

public sealed class PathSet
{
    public override string ToString() => Catzc.Base.Objects.ConsoleText.ToConsoleString(this);

    private readonly SortedSet<string> paths = new SortedSet<string>(StringComparer.Ordinal);

    // The number of paths in the set.
    public int Count => paths.Count;

    // A file under a base, whether or not it exists: a missing input is an input too, so a stamp over the set sees it appear.
    public PathSet AddFile(string baseFolder, string relativePath)
    {
        if (string.IsNullOrEmpty(baseFolder)) { throw new ArgumentException("baseFolder must not be empty", "baseFolder"); }
        if (string.IsNullOrEmpty(relativePath)) { throw new ArgumentException("relativePath must not be empty", "relativePath"); }
        paths.Add(Path.GetFullPath(Path.Combine(baseFolder, relativePath)));
        return this;
    }

    public PathSet AddPattern(string folder, string pattern, int depth = 1)
    {
        if (string.IsNullOrEmpty(folder)) { throw new ArgumentException("folder must not be empty", "folder"); }
        if (string.IsNullOrEmpty(pattern)) { throw new ArgumentException("pattern must not be empty", "pattern"); }
        if (!Directory.Exists(folder)) { return this; }
        foreach (string file in FolderWalker.Walk(folder, depth, new[] { pattern }, true, false, null))
        {
            paths.Add(Path.GetFullPath(file));
        }
        return this;
    }

    // The paths in ordinal order, each once.
    public string[] ToArray()
    {
        string[] result = new string[paths.Count];
        paths.CopyTo(result);
        return result;
    }
}
