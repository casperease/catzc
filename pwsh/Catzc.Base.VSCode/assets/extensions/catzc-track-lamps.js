const key = (text) => (FOLD ? text.toLowerCase() : text);
const isGlob = (entry) => /[*?]/.test(entry);

// A path test for a glob, read the way the repository's GlobPattern reads one: '/'-separated segments, '**' a whole segment standing for
// any depth, '*' and '?' inside one segment only. The glob's literal leading segments reject a path before any wildcard is tried, and a
// caller testing many globs passes the path's segments, split once.
function globMatcher(glob) {
    const flags = FOLD ? "i" : "";
    const raw = glob.split("/");
    const segments = raw.map((segment) =>
        segment === "**"
            ? null
            : new RegExp(
                  `^${segment
                      .replace(/[.+^${}()|[\]\\]/g, "\\$&")
                      .replace(/\*/g, "[^/]*")
                      .replace(/\?/g, "[^/]")}$`,
                  flags,
              ),
    );
    const literal = [];
    for (const segment of raw) {
        if (isGlob(segment)) break;
        literal.push(key(segment));
    }
    const from = (at, parts, index) => {
        for (; at < segments.length; at++, index++) {
            if (segments[at] === null) {
                if (at === segments.length - 1) return true;
                for (let skip = index; skip <= parts.length; skip++) if (from(at + 1, parts, skip)) return true;
                return false;
            }
            if (index >= parts.length || !segments[at].test(parts[index])) return false;
        }
        return index === parts.length;
    };
    return (place, parts = place.split("/")) => {
        for (let at = 0; at < literal.length; at++) if (key(parts[at] ?? "") !== literal[at]) return false;
        return from(0, parts, 0);
    };
}

// A claim test for a filter's sets: a set claims a path that one of its includes matches and none of its excludes does. Each include is
// filed under its first literal segment, so a path is tried only against the includes that can match it; one that opens with a wildcard
// is tried against every path.
function claimer(sets) {
    const buckets = new Map();
    const wild = [];
    for (const set of sets) {
        const excludes = (set.exclude ?? []).map(globMatcher);
        for (const include of set.include ?? []) {
            const entry = { matches: globMatcher(include), excludes };
            const first = include.split("/")[0];
            if (isGlob(first)) wild.push(entry);
            else {
                const at = key(first);
                if (!buckets.has(at)) buckets.set(at, []);
                buckets.get(at).push(entry);
            }
        }
    }
    const tries = (entries, place, parts) =>
        entries.some(({ matches, excludes }) => matches(place, parts) && !excludes.some((excluded) => excluded(place, parts)));
    return (place, parts = place.split("/")) => tries(buckets.get(key(parts[0])) ?? [], place, parts) || tries(wild, place, parts);
}

// A claim test for written entries, read as the Explorer reads them: an entry hides what it matches and everything under it, so a path
// is claimed when it or one of its folders is a written path or matches a written glob.
function entryClaimer(entries) {
    const places = new Set(entries.filter((entry) => !isGlob(entry)).map(key));
    const matchers = entries.filter(isGlob).map(globMatcher);
    return (place) => {
        for (let at = place; at !== "."; at = path.posix.dirname(at)) {
            if (places.has(key(at))) return true;
            const parts = at.split("/");
            if (matchers.some((matches) => matches(at, parts))) return true;
        }
        return false;
    };
}

// Every lamp's sets: the open lamp's first, one include per file open in an editor; the declared filters' in their order; and the
// languages lamp's, one include per extension of each typed language (a language it does not know adds nothing).
function lampSets(declared, field, known, open = []) {
    const extensions = typed(field).flatMap((name) => known[name] ?? []);
    return {
        [OPEN]: [{ include: [...open], exclude: [] }],
        ...declared,
        [LANGUAGE]: [{ include: extensions.map((extension) => `**/*${extension}`), exclude: [] }],
    };
}

// The lamp language. sets: each lamp's sets; lit: the lamps on; files: the paths on disk; facts: path -> { change, fault }, where change
// is none, staged or unstaged and fault none or failed. Returns the files shown (the total union: any lit lamp claims it, or no lamp
// does), the files no lamp claims, each file's signature (the lamps claiming it, in lamp order), and each lamp's condition, the highest
// fact over the files it claims by the one precedence, or empty for a lamp whose sets include nothing. A fact's path need not be on disk
// (a deleted file is a change), and the switch never touches a condition. A vetoed lamp (unlit, and hiding its whole zone) takes out every
// file it claims, even one a lit lamp claims too: the shown files are the lit union minus the vetoed zones.
function evaluate(sets, lit, files, facts = {}, vetoed = []) {
    const vetoes = new Set(vetoed);
    const names = Object.keys(sets);
    const claims = names.map((name) => [name, claimer(sets[name])]);
    const signatureOf = (place) => {
        const parts = place.split("/");
        return claims.filter(([, claimed]) => claimed(place, parts)).map(([name]) => name);
    };
    const shown = [];
    const unaccounted = [];
    const signatures = {};
    for (const place of files) {
        const signature = signatureOf(place);
        signatures[place] = signature;
        if (signature.length === 0) unaccounted.push(place);
        if (signature.some((name) => vetoes.has(name))) continue;
        if (signature.length === 0 || signature.some((name) => lit.has(name))) shown.push(place);
    }
    const rank = Object.fromEntries(names.map((name) => [name, 0]));
    for (const [place, fact] of Object.entries(facts)) {
        const level = fact?.fault === "failed" ? 3 : fact?.change === "unstaged" ? 2 : fact?.change === "staged" ? 1 : 0;
        if (level === 0) continue;
        for (const name of signatures[place] ?? signatureOf(place)) rank[name] = Math.max(rank[name], level);
    }
    const empty = (name) => sets[name].every((set) => (set.include ?? []).length === 0);
    const conditions = Object.fromEntries(names.map((name) => [name, empty(name) ? EMPTY : CONDITIONS[rank[name]]]));
    return { shown, unaccounted, signatures, conditions };
}

// The files and the folders on disk, '/'-separated from the root, in one walk; .git is no part of the tree.
async function walkDisk(root) {
    const files = [];
    const folders = [];
    const walk = async (folder) => {
        let found;
        try {
            found = await fs.promises.readdir(path.join(root, folder), { withFileTypes: true });
        } catch {
            return;
        }
        for (const entry of found) {
            const place = folder === "." ? entry.name : `${folder}/${entry.name}`;
            if (place === ".git") continue;
            if (entry.isDirectory()) {
                folders.push(place);
                await walk(place);
            } else files.push(place);
        }
    };
    await walk(".");
    return { files, folders };
}

// A file's extension as written ('.ps1'), empty for none, a dotfile, or one a glob would read as a pattern.
const extensionOf = (place) => {
    const name = path.posix.basename(place);
    const at = name.lastIndexOf(".");
    const extension = at > 0 ? name.slice(at) : "";
    return /[*?[\]{}!,]/.test(extension) ? "" : extension;
};

// The entries that hide what the tree does not show, as few as the shown files allow, since the editor hands files.exclude to the
// processes it spawns and a long list overflows their command line. A folder that shows no file is written whole, as its topmost such
// folder (so a dead folder, emptied by the lamps or empty on disk, leaves the tree too). A hidden file in a shown folder rides on its
// extension where no shown file shares it: '**/*<ext>' when none does anywhere, else '<folder>/**/*<ext>' for its topmost folder holding
// none; otherwise it is written itself, in its on-disk spelling.
function hiddenEntries(files, folders, shown) {
    const live = new Set();
    for (const place of shown) for (let at = path.posix.dirname(place); at !== "."; at = path.posix.dirname(at)) live.add(at);
    const showing = new Set(shown);
    const topmostDead = (place) => {
        let dead;
        for (let at = path.posix.dirname(place); at !== "."; at = path.posix.dirname(at)) if (!live.has(at)) dead = at;
        return dead;
    };
    // Each extension's folders that hold a shown file or a live folder of it (a glob hides a folder whose name it matches), at any depth,
    // the root as '.'.
    const shownUnder = new Set();
    for (const place of [...shown, ...live]) {
        const extension = key(extensionOf(place));
        if (!extension) continue;
        shownUnder.add(`${extension}|.`);
        for (let at = path.posix.dirname(place); at !== "."; at = path.posix.dirname(at)) shownUnder.add(`${extension}|${key(at)}`);
    }
    const rollUp = (place) => {
        const extension = extensionOf(place);
        if (!extension) return place;
        if (!shownUnder.has(`${key(extension)}|.`)) return `**/*${extension}`;
        const parts = place.split("/");
        for (let depth = 1; depth < parts.length; depth++) {
            const folder = parts.slice(0, depth).join("/");
            if (!shownUnder.has(`${key(extension)}|${key(folder)}`)) return `${folder}/**/*${extension}`;
        }
        return place;
    };
    // A dead folder below the root rides on its name the same way: '**/<name>' where no live folder and no shown file bears it, else
    // '<folder>/**/<name>' for its topmost folder holding none; otherwise it is written itself.
    const namedUnder = new Set();
    for (const place of [...shown, ...live]) {
        const name = key(path.posix.basename(place));
        namedUnder.add(`${name}|.`);
        for (let at = path.posix.dirname(place); at !== "."; at = path.posix.dirname(at)) namedUnder.add(`${name}|${key(at)}`);
    }
    const deadEntry = (folder) => {
        const name = path.posix.basename(folder);
        if (!folder.includes("/") || /[*?[\]{}!,]/.test(name)) return folder;
        if (!namedUnder.has(`${key(name)}|.`)) return `**/${name}`;
        const parts = folder.split("/");
        for (let depth = 1; depth < parts.length - 1; depth++) {
            const above = parts.slice(0, depth).join("/");
            if (!namedUnder.has(`${key(name)}|${key(above)}`)) return `${above}/**/${name}`;
        }
        return folder;
    };
    const entries = new Set();
    for (const place of files) if (!showing.has(place)) {
        const dead = topmostDead(place);
        entries.add(dead ? deadEntry(dead) : rollUp(place));
    }
    // A folder with no file below it at all stays in the tree: no lamp claims it, so nothing hides it (DDR-FILTER-EVERYFILECLAIMED), and
    // writing it would cost an entry in every state. A folder the lamps emptied holds files, so it still leaves the tree.
    const populated = new Set();
    for (const place of files) for (let at = path.posix.dirname(place); at !== "."; at = path.posix.dirname(at)) populated.add(at);
    for (const place of folders) if (!live.has(place) && populated.has(place)) entries.add(deadEntry(topmostDead(place) ?? place));
    return [...entries].sort();
}

// The entries for the unlit lamps, from one walk of the disk: out holds the unlit lamps, field the languages typed for the languages lamp,
// open the files open in an editor, vetoed the unlit lamps that also hide their whole zone. Every lamp lit writes nothing, as without the
// extension.
// disk is the extension's in-memory index of the walk ({ files, folders }); without it the disk is walked, as the tests do.
async function hiddenGlobs(root, out, field, declared, known, open = [], vetoed = [], disk = undefined) {
    const sets = lampSets(declared, field, known, open);
    const lit = new Set(Object.keys(sets).filter((name) => !out.has(name)));
    if (lit.size === Object.keys(sets).length) return [];
    const { files, folders } = disk ?? (await walkDisk(root));
    return hiddenEntries(files, folders, evaluate(sets, lit, files, {}, vetoed).shown);
}

// Every file on disk accounted for: the written entries must hide exactly the files the language does not show. Returns the totals, the
// files shown, the files per signature, the files no lamp claims, and the files whose visibility breaks the rule.
async function census(root, out, field, declared, known, globs, open = [], vetoed = [], disk = undefined) {
    const sets = lampSets(declared, field, known, open);
    const lit = new Set(Object.keys(sets).filter((name) => !out.has(name)));
    const { files } = disk ?? (await walkDisk(root));
    const verdict = evaluate(sets, lit, files, {}, vetoed);
    const showing = new Set(verdict.shown);
    const written = entryClaimer(globs);
    const result = { total: files.length, shown: 0, signatures: {}, unclaimed: verdict.unaccounted, wrong: [] };
    for (const place of files) {
        const signature = verdict.signatures[place];
        const label = signature.length ? signature.join("+") : "(none)";
        result.signatures[label] = (result.signatures[label] ?? 0) + 1;
        const hidden = written(place, place.split("/"));
        if (!hidden) result.shown++;
        if (hidden === showing.has(place)) result.wrong.push(place);
    }
    return result;
}

// A path of the editor's, made '/'-separated from the root; undefined when it lies outside the root.
function relativeTo(root, fsPath) {
    const relative = path.relative(root, fsPath);
    if (!relative || relative.startsWith("..") || path.isAbsolute(relative)) return undefined;
    return relative.split(path.sep).join("/");
}

// The facts in one map, a file's change and fault side by side; unstaged outranks staged for a file in both lists.
function addFact(facts, place, field, value) {
    if (!place) return;
    const fact = (facts[place] ??= {});
    if (field === "change" && fact.change === "unstaged") return;
    fact[field] = value;
}

// The change facts from the git extension's repository state: staged for the index's changes, unstaged for the working tree's, the
// untracked and the merge changes.
function gitFacts(root, state, facts = {}) {
    for (const change of state?.indexChanges ?? []) addFact(facts, relativeTo(root, change.uri.fsPath), "change", "staged");
    for (const list of [state?.workingTreeChanges, state?.untrackedChanges, state?.mergeChanges])
        for (const change of list ?? []) addFact(facts, relativeTo(root, change.uri.fsPath), "change", "unstaged");
    return facts;
}

// The fault facts from the diagnostics, [uri, diagnostics] pairs: failed for a file carrying an Error (severity 0).
function diagnosticFacts(root, entries, facts = {}) {
    for (const [uri, diagnostics] of entries ?? [])
        if ((diagnostics ?? []).some((diagnostic) => diagnostic.severity === 0))
            addFact(facts, relativeTo(root, uri.fsPath), "fault", "failed");
    return facts;
}

// The places carrying an Error right now, for the log line that tells a held fault from a live one.
function errorPlaces(root, entries) {
    return (entries ?? [])
        .filter(([, diagnostics]) => (diagnostics ?? []).some((diagnostic) => diagnostic.severity === 0))
        .map(([uri]) => relativeTo(root, uri.fsPath))
        .filter(Boolean)
        .sort();
}

// An Error as it is stored and published again: its message, range (start line and character, end line and character), source and code.
function storedError(diagnostic) {
    const { start, end } = diagnostic.range ?? {};
    const code = typeof diagnostic.code === "object" ? diagnostic.code?.value : diagnostic.code;
    return {
        message: diagnostic.message ?? "",
        range: [start?.line ?? 0, start?.character ?? 0, end?.line ?? 0, end?.character ?? 0],
        source: diagnostic.source ?? "error",
        code: code === undefined ? undefined : String(code),
    };
}

// A diagnostic this extension published for a closed file's remembered Error; the live diagnostics are read without them.
const isRemembered = (diagnostic) => typeof diagnostic.source === "string" && diagnostic.source.endsWith(REMEMBERED);

// The files whose Error stays a fault while the editor's diagnostics fall silent: a language server reports a file's Error only while the
// file is open (a closed preview tab clears it) and while it is not re-analysing, and red always wins over the change colours. held maps
// a place to { seen: the time its Error was first seen, diagnostics: its Errors as last reported }; the fault stays until the file
// reports a non-error set, is edited or saved (the caller), or changes on disk after that time (lapsed); silence and a closed tab never
// release it. Returns the new map.
function heldFaults(root, held, entries, now = Date.now()) {
    const next = { ...(held ?? {}) };
    for (const [uri, diagnostics] of entries ?? []) {
        const place = relativeTo(root, uri.fsPath);
        if (!place) continue;
        const list = diagnostics ?? [];
        const errors = list.filter((diagnostic) => diagnostic.severity === 0);
        if (errors.length > 0) next[place] = { seen: next[place]?.seen ?? now, diagnostics: errors.slice(0, MAX_REMEMBERED).map(storedError) };
        else if (list.length > 0) delete next[place];
    }
    return next;
}

// The held places whose file changed on disk after its Error was seen, or is gone: the held map without them.
async function lapsedFaults(root, held) {
    const next = { ...held };
    for (const [place, fault] of Object.entries(held)) {
        try {
            if ((await fs.promises.stat(path.join(root, place))).mtimeMs > fault.seen) delete next[place];
        } catch {
            delete next[place];
        }
    }
    return next;
}

// The Errors to publish again: the held places the language servers report no Error for now, each with its stored Errors. A place with a
// live Error is left to its server, so nothing shows twice.
function remembering(root, held, entries) {
    const live = new Set(errorPlaces(root, entries));
    return Object.fromEntries(Object.entries(held ?? {}).filter(([place]) => !live.has(place)).map(([place, fault]) => [place, fault.diagnostics]));
}

// The module a test file tests: the folder above its first tests segment, else its own folder.
function testedModule(test) {
    const parts = test.split("/");
    const at = parts.indexOf("tests");
    return (at > 0 ? parts.slice(0, at) : parts.slice(0, -1)).join("/") || ".";
}

// The fault facts from the test-result markers, out/test-results/<test file>.failed: a marker makes its test file failed while it is
// newer than the test file and every file of the module it tests, so an edit after the run lapses it. Existence and timestamps only.
async function markerFacts(root, facts = {}) {
    const markers = (await walkDisk(path.join(root, MARKERS))).files.filter((place) => place.endsWith(".failed"));
    const newest = async (folder) => {
        let latest = 0;
        for (const place of (await walkDisk(path.join(root, folder))).files) {
            try {
                latest = Math.max(latest, (await fs.promises.stat(path.join(root, folder, place))).mtimeMs);
            } catch {}
        }
        return latest;
    };
    for (const marker of markers) {
        const test = marker.slice(0, -".failed".length);
        let written;
        let tested;
        try {
            written = (await fs.promises.stat(path.join(root, MARKERS, marker))).mtimeMs;
            tested = (await fs.promises.stat(path.join(root, test))).mtimeMs;
        } catch {
            continue;
        }
        const module = testedModule(test);
        if (written > tested && (module === "." || written > (await newest(module)))) addFact(facts, test, "fault", "failed");
    }
    return facts;
}

// The next files.exclude: the current one without the keys the lamps added before, plus the wanted entries. An entry the settings
// already carry is theirs, never the lamps', so the lamps own only the keys they add.
function merge(current, owned, wanted) {
    const authored = { ...current };
    owned.forEach((glob) => delete authored[glob]);
    const ours = wanted.filter((glob) => !(glob in authored));
    const next = { ...authored };
    ours.forEach((glob) => (next[glob] = true));
    return { next, ours };
}

// The files open in an editor, '/'-separated from the root, from the editor's tab groups: a text tab's file, a diff tab's modified side,
// a notebook's file; a tab outside the root or not on disk is none.
function openFiles(root, tabGroups) {
    const open = new Set();
    for (const group of tabGroups ?? [])
        for (const tab of group.tabs ?? []) {
            const uri = tab.input?.modified ?? tab.input?.uri;
            const place = uri?.scheme === "file" ? relativeTo(root, uri.fsPath) : undefined;
            if (place) open.add(place);
        }
    return [...open].sort();
}

// What files.exclude costs on a command line: each glob and a flag with its quotes.
const excludeSize = (exclude) => Object.keys(exclude).reduce((total, glob) => total + glob.length + 6, 0);

// The files.exclude the lamps wrote last, so the settings change their own write raises is not taken for a new one.
let written;

// One pass of the filter for the switches as they are now (state: out, vetoed, field): the entries computed, the settings written when
// they differ. Passes never overlap: the press queue in activate runs one at a time, the latest switches winning, so a slow write of an
// older state can never land after a newer one.
async function apply(context, state, disk) {
    const folder = vscode.workspace.workspaceFolders?.[0];
    if (!folder) {
        return undefined;
    }
    const root = folder.uri.fsPath;
    const out = new Set(state.out);
    const field = state.field;
    const vetoed = new Set(state.vetoed);
    const open = openFiles(root, vscode.window.tabGroups.all);
    const wanted = await hiddenGlobs(root, out, field, filters(), languages(), open, vetoed, disk);
    const files = vscode.workspace.getConfiguration("files", folder.uri);
    const current = files.inspect("exclude")?.workspaceValue ?? {};
    const { next, ours } = merge(current, context.workspaceState.get(OWNED, []), wanted);
    trace(`apply: unlit [${[...out].join(", ")}], vetoed [${[...vetoed].join(", ")}], field "${field}", ${wanted.length} entries wanted, ${ours.length} owned`);
    await context.workspaceState.update(OWNED, ours);
    written = JSON.stringify(next);
    if (written !== JSON.stringify(current)) {
        await files.update("exclude", next, vscode.ConfigurationTarget.Workspace);
        trace(`apply: files.exclude written with ${Object.keys(next).length} keys`);
    }
    const size = excludeSize(next);
    if (size > EXCLUDE_ROOF) {
        log.appendLine(
            `warning: files.exclude is ${size} characters in ${Object.keys(next).length} keys, over the ${EXCLUDE_ROOF} the editor's search and watcher processes take on a command line (spawn ENAMETOOLONG); unlit [${[...out].join(", ")}]`,
        );
    }
    return { root, out, vetoed, field, wanted, open, disk };
}

// The engine: everything the lamps do in the editor. The installed package is a shell that runs the repository's copy of this file and
// swaps it on save (activate below), so a change of logic lands without an install or a reload; api is the shell's vscode module, since
// a file outside the installed package cannot require it itself.
function activateEngine(context, api) {
    vscode = api ?? require("vscode");
    log = vscode.window.createOutputChannel("Catzc track lamps");
    context.subscriptions.push(log);
    let judgeTimer;
    let timer;
    // A swapped-out engine leaves no timer behind to fire into its disposed parts.
    context.subscriptions.push({ dispose: () => (clearTimeout(judgeTimer), clearTimeout(timer)) });
    const lamps = () => assertShipped([OPEN, ...Object.keys(filters()), LANGUAGE]);
    // Every declared lamp, the preview ones included: the title row shows a lamp only while its shown key is set.
    const declaredLamps = () => [OPEN, ...Object.keys(declaredFilters()), LANGUAGE];
    const rootOf = () => vscode.workspace.workspaceFolders?.[0]?.uri.fsPath;

    // The switches, one authoritative copy in memory: a press changes it at once, the workspace state only remembers it across reloads.
    const state = {
        out: new Set(context.workspaceState.get(OUT, [])),
        vetoed: new Set(context.workspaceState.get(VETO, [])),
        field: context.workspaceState.get(FIELD, ""),
    };
    // The disk, indexed once and kept current from the editor's file events, so a press classifies files in memory and never walks the
    // disk; a window focus re-walks it in the background, which also covers the paths files.watcherExclude keeps the events of.
    const index = { files: new Set(), folders: new Set() };
    const rebuild = async () => {
        const root = rootOf();
        if (!root) return;
        const disk = await walkDisk(root);
        index.files = new Set(disk.files);
        index.folders = new Set(disk.folders);
    };
    let indexed = rebuild();
    const snapshot = async () => {
        await indexed;
        return { files: [...index.files], folders: [...index.folders] };
    };
    const indexAdd = async (uri) => {
        const root = rootOf();
        const place = root && relativeTo(root, uri.fsPath);
        if (!place || place === ".git" || place.startsWith(".git/")) return;
        let stat;
        try {
            stat = await fs.promises.stat(uri.fsPath);
        } catch {
            return;
        }
        for (let at = path.posix.dirname(place); at !== "."; at = path.posix.dirname(at)) index.folders.add(at);
        if (!stat.isDirectory()) return void index.files.add(place);
        index.folders.add(place);
        const inner = await walkDisk(uri.fsPath);
        for (const file of inner.files) index.files.add(`${place}/${file}`);
        for (const folder of inner.folders) index.folders.add(`${place}/${folder}`);
    };
    const indexRemove = (uri) => {
        const root = rootOf();
        const place = root && relativeTo(root, uri.fsPath);
        if (!place) return;
        const below = `${place}/`;
        index.files.delete(place);
        index.folders.delete(place);
        for (const file of index.files) if (file.startsWith(below)) index.files.delete(file);
        for (const folder of index.folders) if (folder.startsWith(below)) index.folders.delete(folder);
    };
    // The title row shows each lamp's icon by its context keys: the switch (out: off, veto: vetoed, neither: on) and the condition. Only a
    // key whose value changed is sent, so a press costs the one or two keys it moves.
    let conditions = {};
    let markerCache = null;
    const sent = new Map();
    const setKey = (name, value) => {
        if (sent.get(name) === value) return undefined;
        sent.set(name, value);
        return vscode.commands.executeCommand("setContext", name, value);
    };
    const show = async () => {
        const out = state.out;
        const vetoed = state.vetoed;
        const inPlay = new Set(lamps());
        await Promise.all([
            ...declaredLamps().map((lamp) => setKey(`catzc.lamps.shown.${lamp}`, inPlay.has(lamp))),
            ...[...inPlay].flatMap((lamp) => [
                setKey(`catzc.lamps.out.${lamp}`, out.has(lamp) && !vetoed.has(lamp)),
                setKey(`catzc.lamps.veto.${lamp}`, out.has(lamp) && vetoed.has(lamp)),
                setKey(`catzc.lamps.state.${lamp}`, conditions[lamp] ?? "committed"),
            ]),
        ]);
    };
    // The conditions from the facts the editor already holds; only the facts' paths are classified, so no disk walk is needed.
    let repository;
    let held = context.workspaceState.get(HELD, {});
    // A closed file's remembered Errors, published again as this extension's own diagnostics: the editor's problem decorations are the only
    // ones heavier than the git colours and the only ones that colour every folder above the file, so the Explorer row, the tab and the
    // tree show the same red as for an open file. The language servers' own Errors take over the moment they report again.
    const collection = vscode.languages.createDiagnosticCollection("catzc");
    context.subscriptions.push(collection);
    let published = {};
    const publish = (root, wanted) => {
        for (const place of Object.keys(published)) {
            if (place in wanted) continue;
            collection.delete(vscode.Uri.file(path.join(root, place)));
            delete published[place];
        }
        for (const [place, errors] of Object.entries(wanted)) {
            const signature = JSON.stringify(errors);
            if (published[place] === signature) continue;
            const diagnostics = errors.map((error) => {
                const diagnostic = new vscode.Diagnostic(
                    new vscode.Range(error.range[0], error.range[1], error.range[2], error.range[3]),
                    error.message,
                    vscode.DiagnosticSeverity.Error,
                );
                diagnostic.source = `${error.source}${REMEMBERED}`;
                if (error.code !== undefined) diagnostic.code = error.code;
                return diagnostic;
            });
            collection.set(vscode.Uri.file(path.join(root, place)), diagnostics);
            published[place] = signature;
        }
    };
    const judge = async () => {
        const root = rootOf();
        if (!root) return;
        const facts = gitFacts(root, repository?.state);
        const entries = vscode.languages.getDiagnostics().map(([uri, diagnostics]) => [uri, diagnostics.filter((d) => !isRemembered(d))]);
        const before = JSON.stringify(context.workspaceState.get(HELD, {}));
        held = await lapsedFaults(root, heldFaults(root, held, entries));
        if (JSON.stringify(held) !== before) await context.workspaceState.update(HELD, held);
        const heldPlaces = Object.keys(held).sort();
        diagnosticFacts(root, entries, facts);
        for (const place of heldPlaces) addFact(facts, place, "fault", "failed");
        // The markers are read once and again only when a marker or a file changes, never on each diagnostics event.
        markerCache ??= markerFacts(root, {});
        for (const [place, fact] of Object.entries(await markerCache)) addFact(facts, place, "fault", fact.fault);
        // Every file the lamps hold as failed shows red in the tree: the remembered Errors, and a test file whose run left a failed marker.
        const wanted = remembering(root, held, entries);
        const live = new Set(errorPlaces(root, entries));
        for (const [place, fact] of Object.entries(facts))
            if (fact.fault === "failed" && !(place in wanted) && !live.has(place))
                wanted[place] = [{ message: "its last test run failed", range: [0, 0, 0, 0], source: "tests" }];
        publish(root, wanted);
        const sets = lampSets(filters(), state.field, languages(), openFiles(root, vscode.window.tabGroups.all));
        const next = evaluate(sets, new Set(Object.keys(sets).filter((name) => !state.out.has(name))), [], facts).conditions;
        if (JSON.stringify(next) === JSON.stringify(conditions)) return;
        conditions = next;
        trace(
            `conditions: ${Object.entries(conditions)
                .map(([lamp, condition]) => `${lamp} ${condition}`)
                .join(", ")} | held [${heldPlaces.join(", ")}] | errors [${errorPlaces(root, entries).join(", ")}]`,
        );
        await show();
    };
    const rejudge = () => {
        clearTimeout(judgeTimer);
        judgeTimer = setTimeout(() => judge().catch((error) => log.appendLine(`conditions failed: ${error?.stack ?? error}`)), 300);
    };
    // The counter: shown/total files on disk, green while every file is hidden exactly as its filters say, red with the count when not.
    const counter = vscode.window.createStatusBarItem(vscode.StatusBarAlignment.Left, 100);
    counter.command = "catzc.lamps.showLog";
    counter.text = "$(sync~spin) counting files";
    counter.show();
    context.subscriptions.push(
        counter,
        vscode.commands.registerCommand("catzc.lamps.showLog", () => log.show()),
    );
    const count = async (applied) => {
        if (!applied) return;
        const { root, out, vetoed, field, wanted, open, disk } = applied;
        const tally = await census(root, out, field, filters(), languages(), wanted, open, vetoed, disk);
        const matrix = Object.entries(tally.signatures)
            .sort((a, b) => b[1] - a[1])
            .map(([signature, files]) => `${signature}: ${files}`);
        const lit = lamps().map((lamp) => `${lamp}${out.has(lamp) ? (vetoed.has(lamp) ? " (veto)" : " (off)") : ""} ${conditions[lamp] ?? "committed"}`);
        if (tally.wrong.length === 0 && tally.unclaimed.length === 0) {
            counter.text = `$(pass) ${tally.shown}/${tally.total} · everything is accounted for`;
            counter.color = "#3fb950";
            counter.tooltip = `Catzc lamps: ${tally.shown} of ${tally.total} files shown, each hidden exactly when no lit lamp claims it or a vetoed lamp does.\nLamps: ${lit.join(", ")}\nFiles per signature:\n${matrix.join("\n")}`;
        } else {
            const problems = tally.wrong.length + tally.unclaimed.length;
            counter.text = `$(warning) ${tally.shown}/${tally.total} · a filter went bananas (${problems})`;
            counter.color = "#f85149";
            counter.tooltip = `Catzc lamps: ${tally.wrong.length} files shown or hidden against their filters, e.g. ${tally.wrong.slice(0, 3).join(", ")}; ${tally.unclaimed.length} files no filter claims, e.g. ${tally.unclaimed.slice(0, 3).join(", ")}\nClick for the log.`;
        }
        const line = `census: ${tally.shown}/${tally.total} shown; ${matrix.join(", ")}; ${tally.wrong.length} against their filters` +
            `${tally.wrong.length ? ": " + tally.wrong.slice(0, 20).join(", ") : ""}; ${tally.unclaimed.length} unclaimed` +
            `${tally.unclaimed.length ? ": " + tally.unclaimed.slice(0, 20).join(", ") : ""}`;
        if (tally.wrong.length === 0 && tally.unclaimed.length === 0) trace(line);
        else log.appendLine(`warning: ${line}`);
    };
    // Every failure lands in the output channel; an unhandled rejection would vanish without a trace.
    const settle = async (retried = false) => {
        try {
            const applied = await apply(context, state, await snapshot());
            // The write is verified against what the editor now holds; a mismatch (a write lost to a concurrent edit of the settings) is
            // one more pass, never a silent disagreement between the lamps and the tree.
            const folder = vscode.workspace.workspaceFolders?.[0];
            const now = JSON.stringify(vscode.workspace.getConfiguration("files", folder?.uri).inspect("exclude")?.workspaceValue ?? {});
            if (applied && now !== written) {
                if (!retried) return settle(true);
                log.appendLine(`warning: files.exclude did not take the lamps' write (${now.length} vs ${written.length} characters); the tree may disagree with the lamps`);
            }
            // The count runs after the filter is in place, never delaying it; its failure is logged like any other.
            count(applied).catch((error) => log.appendLine(`census failed: ${error?.stack ?? error}`));
        } catch (error) {
            log.appendLine(`apply failed: ${error?.message ?? error}`);
            // A settings file rewritten on disk meanwhile (a generator's render) is read afresh and written once more, unasked.
            if (!retried && /newer/i.test(`${error?.message ?? ""}`)) {
                await new Promise((resolve) => setTimeout(resolve, 1000));
                return settle(true);
            }
            const message = `Catzc track lamps could not filter: ${error?.message ?? error}`;
            // The editor refuses a settings write while settings.json is open with unsaved edits; saving it is the user's call, offered here.
            const dirty = vscode.workspace.textDocuments.find(
                (document) => document.isDirty && /[\\/]\.vscode[\\/]settings\.json$/i.test(document.uri.fsPath),
            );
            if (dirty) {
                vscode.window.showWarningMessage(message, "Save and filter").then(async (choice) => {
                    if (choice === "Save and filter" && (await dirty.save())) await settle();
                });
            } else {
                vscode.window.showWarningMessage(message);
            }
        }
        await show();
    };
    // The press queue: every press (and every outside event) asks for one pass, and one pass runs at a time over the switches as they are
    // when it starts; a press that lands mid-pass is served by the next pass, so the last press always has the last word and the tree is
    // in the pressed state as soon as the queue drains. The counter spins while it drains.
    let draining = null;
    let pending = false;
    const drain = async () => {
        counter.text = "$(sync~spin) filtering";
        counter.color = undefined;
        while (pending) {
            pending = false;
            await settle();
        }
    };
    const requestApply = () => {
        pending = true;
        if (!draining) {
            draining = drain()
                .catch((error) => log.appendLine(`filtering failed: ${error?.stack ?? error}`))
                .finally(() => {
                    draining = null;
                    if (pending) requestApply();
                });
        }
        return draining;
    };
    // A click steps a lamp round off -> on -> veto -> off: the switch and its icon change at once, the pass is queued, the count follows.
    // A vetoed lamp is unlit as well, so the conditions and the open-lamp refresh read it as off.
    const turn = (lamp, mode) => {
        if (mode === "on") state.out.delete(lamp);
        else state.out.add(lamp);
        if (mode === "veto") state.vetoed.add(lamp);
        else state.vetoed.delete(lamp);
        const remembered = Promise.all([context.workspaceState.update(OUT, [...state.out]), context.workspaceState.update(VETO, [...state.vetoed])]);
        show().catch((error) => log.appendLine(`show failed: ${error?.message ?? error}`));
        rejudge();
        requestApply();
        return remembered;
    };
    // Lighting the languages lamp asks which languages it shows, offering the last list; Escape keeps it unlit.
    const chooseLanguages = async () => {
        const known = Object.keys(languages());
        const answer = await vscode.window.showInputBox({
            title: "Languages to show",
            prompt: `Comma-separated; known: ${known.join(", ")}`,
            value: state.field,
            validateInput: (text) => {
                const unknown = typed(text).filter((name) => !known.includes(name));
                return unknown.length ? `unknown: ${unknown.join(", ")}` : undefined;
            },
        });
        if (answer === undefined) return;
        state.field = typed(answer).join(", ");
        await context.workspaceState.update(FIELD, state.field);
        await turn(LANGUAGE, "on");
    };
    // An outside event (a settings file rendered anew, the window focused) asks for a pass through the same queue, debounced since such
    // events come in bursts; a press never waits.
    const refresh = () => {
        clearTimeout(timer);
        timer = setTimeout(requestApply, 200);
    };

    // A command per lamp state, named for what its click does and shown with the icon of the state it leaves: light (off -> on) and veto
    // (on -> veto) per condition, each its own icon, committed the bare name; putOut (veto -> off) has the one veto icon. The manifest
    // declares the same names (a test holds it to filters.yml and the conditions).
    for (const lamp of lamps()) {
        context.subscriptions.push(vscode.commands.registerCommand(`catzc.lamps.${lamp}.putOut`, () => turn(lamp, "off")));
        for (const condition of [...CONDITIONS, EMPTY]) {
            const suffix = condition === "committed" ? "" : `.${condition}`;
            context.subscriptions.push(
                vscode.commands.registerCommand(`catzc.lamps.${lamp}.veto${suffix}`, () => turn(lamp, "veto")),
                vscode.commands.registerCommand(
                    `catzc.lamps.${lamp}.light${suffix}`,
                    lamp === LANGUAGE ? chooseLanguages : () => turn(lamp, "on"),
                ),
            );
        }
    }
    // The facts' sources: the git extension's repository state, the diagnostics, the markers, and a save (a marker lapses by timestamp).
    const watchGit = async () => {
        const extension = vscode.extensions.getExtension("vscode.git");
        if (!extension) return log.appendLine("conditions: no git extension, so no change facts");
        const api = (extension.isActive ? extension.exports : await extension.activate()).getAPI(1);
        const attach = () => {
            const root = key(rootOf() ?? "");
            const found = api.repositories.find((candidate) => key(candidate.rootUri.fsPath) === root) ?? api.repositories[0];
            if (!found || found === repository) return;
            repository = found;
            context.subscriptions.push(repository.state.onDidChange(rejudge));
            rejudge();
        };
        context.subscriptions.push(api.onDidOpenRepository(attach));
        attach();
    };
    watchGit().catch((error) => log.appendLine(`git facts failed: ${error?.stack ?? error}`));
    const folder = vscode.workspace.workspaceFolders?.[0];
    if (folder) {
        const markers = vscode.workspace.createFileSystemWatcher(new vscode.RelativePattern(folder, `${MARKERS}/**`));
        const remark = () => ((markerCache = null), rejudge());
        context.subscriptions.push(markers, markers.onDidCreate(remark), markers.onDidChange(remark), markers.onDidDelete(remark));
        // Every file created or deleted keeps the index current; the tree follows while a lamp is unlit, and a marker may lapse.
        const anything = vscode.workspace.createFileSystemWatcher(new vscode.RelativePattern(folder, "**"), false, true, false);
        const touched = () => {
            markerCache = null;
            if (state.out.size > 0) refresh();
        };
        context.subscriptions.push(
            anything,
            anything.onDidCreate((uri) => indexAdd(uri).then(touched)),
            anything.onDidDelete((uri) => (indexRemove(uri), touched())),
        );
    }
    // An edit or a save releases the file's held Error (its diagnostics re-hold it while it still has one); switching the active file
    // re-judges, so the open lamp follows the red file that was just left.
    const release = (document) => {
        const root = rootOf();
        const place = root && document.uri.scheme === "file" ? relativeTo(root, document.uri.fsPath) : undefined;
        if (place && place in held) {
            held = { ...held };
            delete held[place];
        }
        rejudge();
    };
    context.subscriptions.push(
        vscode.languages.onDidChangeDiagnostics(rejudge),
        vscode.window.onDidChangeActiveTextEditor(rejudge),
        vscode.workspace.onDidChangeTextDocument((event) => event.contentChanges.length > 0 && release(event.document)),
        vscode.workspace.onDidSaveTextDocument((document) => ((markerCache = null), release(document))),
    );
    // An opened or closed editor changes the open lamp's files: its condition at once, and the tree while a lamp is unlit.
    context.subscriptions.push(
        vscode.window.tabGroups.onDidChangeTabs(() => {
            rejudge();
            if (state.out.size > 0) refresh();
        }),
    );
    context.subscriptions.push(
        vscode.workspace.onDidChangeConfiguration((event) => {
            if (event.affectsConfiguration("catzc.trackLamps")) {
                rejudge();
                return refresh();
            }
            if (!event.affectsConfiguration("files.exclude")) return;
            // The lamps' own write echoes back as a change; only a change made elsewhere (a regenerated settings file) is re-applied.
            const folder = vscode.workspace.workspaceFolders?.[0];
            const now = JSON.stringify(vscode.workspace.getConfiguration("files", folder?.uri).inspect("exclude")?.workspaceValue ?? {});
            if (now !== written) refresh();
        }),
        vscode.window.onDidChangeWindowState((window) => {
            if (!window.focused) return;
            markerCache = null;
            indexed = rebuild().then(refresh);
        }),
    );
    refresh();
    rejudge();
}

// The engine's file in the repository, as the shell finds it under the workspace folder.
const ENGINE = "pwsh/Catzc.Base.VSCode/assets/extensions/catzc-track-lamps.js";

// The shell, which is all the installed package does: it runs the repository's engine, so the engine is always the working tree's, and
// on a save of that file it disposes the running engine and starts the new one with the same remembered state, without an install or a
// window reload. A package change (new commands, icons, menu entries) still takes a reinstall and a reload. Outside this repository, or
// when the repository's engine fails to load, the package's own copy runs.
function activate(context) {
    const api = require("vscode");
    const root = api.workspace.workspaceFolders?.[0]?.uri.fsPath;
    const source = root ? path.join(root, ENGINE) : undefined;
    const same = (a, b) => key(path.resolve(a)) === key(path.resolve(b));
    if (!source || !fs.existsSync(source) || same(source, __filename)) return activateEngine(context, api);
    const shellLog = api.window.createOutputChannel("Catzc track lamps (shell)");
    let running;
    const stop = () => {
        for (const part of running?.subscriptions ?? []) {
            try {
                part.dispose();
            } catch {}
        }
        running = undefined;
    };
    const start = () => {
        const engineContext = { subscriptions: [], workspaceState: context.workspaceState, globalState: context.globalState, extensionPath: context.extensionPath, extensionUri: context.extensionUri };
        try {
            delete require.cache[require.resolve(source)];
            require(source).activateEngine(engineContext, api);
        } catch (error) {
            for (const part of engineContext.subscriptions) {
                try {
                    part.dispose();
                } catch {}
            }
            engineContext.subscriptions.length = 0;
            shellLog.appendLine(`error: the repository's engine did not load, the package's copy runs instead: ${error?.stack ?? error}`);
            activateEngine(engineContext, api);
        }
        running = engineContext;
    };
    start();
    let swap;
    const watcher = api.workspace.createFileSystemWatcher(new api.RelativePattern(root, ENGINE));
    const restart = () => {
        clearTimeout(swap);
        swap = setTimeout(() => (stop(), start()), 300);
    };
    context.subscriptions.push(shellLog, watcher, watcher.onDidChange(restart), watcher.onDidCreate(restart), {
        dispose: () => (clearTimeout(swap), stop()),
    });
}

