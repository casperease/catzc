using System;

namespace Catzc.Base.QualityGates;

public sealed class LinkEndpoint
{
    public override string ToString() => Catzc.Base.Objects.ConsoleText.ToConsoleString(this);

    public string Path { get; }
    // The file kind's role, or role/subkind.
    public string Class { get; }
    public string Aspect { get; }
    public string Track { get; }
    public string TrackType { get; }
    public string Module { get; }

    public LinkEndpoint(string path, string @class, string aspect, string track, string trackType, string module)
    {
        if (string.IsNullOrEmpty(path))
        {
            throw new ArgumentException("An endpoint is a repository path.", nameof(path));
        }
        Path = path;
        Class = @class ?? string.Empty;
        Aspect = aspect ?? string.Empty;
        Track = track ?? string.Empty;
        TrackType = trackType ?? string.Empty;
        Module = module ?? string.Empty;
    }
}
