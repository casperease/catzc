using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace Catzc.Base.QualityGates;

public sealed class LinkSelector
{
    public override string ToString() => Catzc.Base.Objects.ConsoleText.ToConsoleString(this);

    static readonly string[] Keys = { "classes", "aspects", "tracks", "track_types", "modules" };

    public IReadOnlyList<string> classes { get; }
    public IReadOnlyList<string> aspects { get; }
    public IReadOnlyList<string> tracks { get; }
    public IReadOnlyList<string> track_types { get; }
    public IReadOnlyList<string> modules { get; }

    public LinkSelector(IDictionary raw, string where)
    {
        var lists = Keys.ToDictionary(k => k, _ => (IReadOnlyList<string>)Array.Empty<string>(), StringComparer.Ordinal);
        if (raw != null)
        {
            foreach (object key in raw.Keys)
            {
                string name = Convert.ToString(key, CultureInfo.InvariantCulture);
                if (!lists.ContainsKey(name))
                {
                    throw new ArgumentException(string.Format(CultureInfo.InvariantCulture,
                        "{0}: unknown key '{1}' (allowed: {2})", where, name, string.Join(", ", Keys)));
                }
                lists[name] = Values(raw[key], where + "." + name, name == "classes");
            }
        }
        classes = lists["classes"];
        aspects = lists["aspects"];
        tracks = lists["tracks"];
        track_types = lists["track_types"];
        modules = lists["modules"];
    }

    static IReadOnlyList<string> Values(object value, string where, bool isClass)
    {
        if (value == null) { return Array.Empty<string>(); }
        IEnumerable items = value is string single ? new[] { single } : value as IEnumerable
            ?? throw new ArgumentException(where + ": must be a list of values");
        var result = new List<string>();
        foreach (object item in items)
        {
            string text = Convert.ToString(item, CultureInfo.InvariantCulture) ?? string.Empty;
            int stars = text.Count(c => c == '*');
            if (text.Length == 0 || text.IndexOfAny(new[] { '?', '[', '{' }) >= 0 || stars > (isClass ? 1 : 0))
            {
                throw new ArgumentException(string.Format(CultureInfo.InvariantCulture,
                    "{0}: '{1}' is no facet value (a selector holds no glob; a class takes at most one '*')", where, text));
            }
            result.Add(text);
        }
        return result;
    }

    public bool Matches(LinkEndpoint endpoint)
    {
        if (endpoint == null) { return false; }
        return (classes.Count == 0 || classes.Any(c => ClassMatches(c, endpoint.Class)))
            && In(aspects, endpoint.Aspect) && In(tracks, endpoint.Track) && In(track_types, endpoint.TrackType) && In(modules, endpoint.Module);
    }

    static bool In(IReadOnlyList<string> values, string facet) =>
        values.Count == 0 || values.Contains(facet, StringComparer.Ordinal);

    static bool ClassMatches(string pattern, string value)
    {
        int star = pattern.IndexOf('*');
        if (star < 0)
        {
            return string.Equals(pattern, value, StringComparison.Ordinal) || value.StartsWith(pattern + "/", StringComparison.Ordinal);
        }
        string head = pattern.Substring(0, star);
        string tail = pattern.Substring(star + 1);
        return value.Length >= head.Length + tail.Length
            && value.StartsWith(head, StringComparison.Ordinal) && value.EndsWith(tail, StringComparison.Ordinal);
    }
}
