    }

    It 'skips files a step found current, and checks them all again when a file its stamp reads changes' -Tag 'ADR-AUTO-CACHE-CHECKEDFILESACROSSSESSIONS' {
        $null = Format-Code -DryRun
        $script:stepRuns.Clear()
