        Mock Invoke-FormatterEngine -ModuleName Catzc.Base.QualityGates { , [string[]] @() }
        Mock Get-ImprintStepFile -ModuleName Catzc.Base.QualityGates { , [string[]] @($script:stepFiles[$Step]) }
