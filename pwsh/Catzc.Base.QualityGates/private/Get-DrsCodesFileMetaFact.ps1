function Get-DrsCodesFileMetaFact {
    [CmdletBinding()]
    [OutputType([System.Collections.Specialized.OrderedDictionary])]
    param(
        [Parameter(Mandatory)]
        [pscustomobject] $State,

        [Parameter(Mandatory)]
        [string] $Path,

        [Parameter(Mandatory)]
        [Catzc.Base.QualityGates.FileMetaKind] $Kind
    )

    $text = if ($State.PSObject.Properties['Body']) {
        $State.Body
    }
    else {
        $State.Rest
    }
    $repositoryRoot = Get-RepositoryRoot
    $page = Get-CommentPage -Path $Path -Config (Get-Config -Config comment-pages)
    if ($page -and (Test-Path -LiteralPath (Join-Path $repositoryRoot $page) -PathType Leaf)) {
        $text += "`n" + (Get-MarkdownMetaState -Text ([System.IO.File]::ReadAllText((Join-Path $repositoryRoot $page)))).Body
    }

    $fileClass = (Get-FileKind $Path).Class
    $withDomain = [Catzc.Base.QualityGates.FileMetaKind]::InClasses($Kind.ClassSetting('domain_classes'), $fileClass)
    $map = Get-DrsCitationMap -RepositoryRoot $repositoryRoot
    $form = (Get-Config -Config drs).CodeForm
    $defined = if ($withDomain) {
        @()
    }
    else {
        @(Get-DrsDefinedRule -Text $text)
    }
    $collect = {
        param([string] $Source)
        $found = [System.Collections.Generic.SortedSet[string]]::new([System.StringComparer]::Ordinal)
        foreach ($match in [regex]::Matches($Source, "(?<![\w-])$($form.Cited)(?![\w#-]|:\d)")) {
            [void] $found.Add($match.Value)
        }
        foreach ($rule in $defined) {
            [void] $found.Remove($rule)
        }
        # Only a code the ADR index registers is a citation: a fixture code or a placeholder named in prose is not. A bare record code is one
        # in every class, except the record the file itself defines rules of; a bare domain code only in a code class.
        foreach ($code in @($found)) {
            $own = @($defined | Where-Object { $_.StartsWith("$code-", [System.StringComparison]::Ordinal) }).Count -gt 0
            $registered = $map.IsRule($code) -or ($map.HasCode($code) -and -not $own) -or ($withDomain -and $map.IsDomainCode($code))
            if (-not $registered) {
                [void] $found.Remove($code)
            }
        }
        , $found
    }
    # The head cites what the prose cites; a ```yml drawio block's codes are the diagram's, counted in the total only.
    $prose = [regex]::Replace($text, '(?m)^```yml drawio[ \t]*\r?\n(?:(?!```).*\r?\n)*```[ \t]*$', '')
    $cited = & $collect $prose
    $total = (& $collect $text).Count
    [ordered]@{
        $Kind.keys[0] = [string[]] @($form.Minimize([string[]] @($cited), $map))
        $Kind.keys[1] = $total -gt 0 ? $total : ''
    }
}
