# -DryRun, not ShouldProcess or -WhatIf: the branch comes before any side effect.
function Install-Catzc {
    [CmdletBinding(DefaultParameterSetName = 'Root')]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory, Position = 0, ParameterSetName = 'Root')]
        [string] $Root,

        [Parameter(Mandatory, ParameterSetName = 'Scope')]
        [ValidateSet('CurrentUser')]
        [string] $Scope,

        [string] $Bundle = "$((Get-Config -Config exporter).default_bundle)",

        [string] $Source = (Join-Path (Get-OutputRoot) "pwsh/built/$Bundle/Catzc/$((Get-Config -Config exporter).direct_install_version)"),
        [switch] $Force,
        [switch] $DryRun,
        [switch] $Silent
    )

    Assert-CatzcBundle -Path $Source

    $sourceBuild = [System.IO.File]::ReadAllText((Join-Path $Source 'build.json')) | ConvertFrom-Json
    $version = "$($sourceBuild.version)"
    $sourceHash = "$($sourceBuild.contentHash)"

    $importer = $null
    if ($Scope -eq 'CurrentUser') {
        $moduleTarget = Join-Path (Get-UserModulePath) "Catzc/$version"
    }
    else {
        $moduleTarget = Join-Path $Root ".vendor/Catzc/$version"
        $importer = Join-Path $Root 'importer.ps1'
    }

    $targetBuild = Join-Path $moduleTarget 'build.json'
    $upToDate = $false
    if ([System.IO.File]::Exists($targetBuild)) {
        $upToDate = "$(([System.IO.File]::ReadAllText($targetBuild) | ConvertFrom-Json).contentHash)" -eq $sourceHash
    }
    $copy = $Force -or -not $upToDate

    if (-not $DryRun) {
        if ($copy) {
            if ([System.IO.Directory]::Exists($moduleTarget)) {
                [System.IO.Directory]::Delete($moduleTarget, $true)
            }
            Copy-Directory -Path $Source -Destination $moduleTarget
            # A copy drops the executable bit, which an engine whose scripts need it (bash) requires on Unix.
            if (-not $IsWindows) {
                $execute = [System.IO.UnixFileMode]::UserExecute -bor [System.IO.UnixFileMode]::GroupExecute -bor [System.IO.UnixFileMode]::OtherExecute
                foreach ($engine in @([Catzc.Base.Engines.ExecutionEngines]::All | Where-Object RequiresExecutableBit)) {
                    foreach ($extension in $engine.ScriptExtensions) {
                        # A named whole-tree walk: every shebang script of the installed module is re-marked.
                        foreach ($script in Get-ChildPath $moduleTarget -File -Filter "*$extension" -Depth 64 -Exclude @() -PruneVendor $false) {
                            # The reader is disposed here, since a pipeline cut short by Select-Object -First leaves a ReadLines enumerator holding the file open.
                            $reader = [System.IO.StreamReader]::new($script)
                            try {
                                $first = $reader.ReadLine()
                            }
                            finally {
                                $reader.Dispose()
                            }
                            if ($null -ne $first -and $first.StartsWith('#!')) {
                                [System.IO.File]::SetUnixFileMode($script,
                                    [System.IO.File]::GetUnixFileMode($script) -bor $execute)
                            }
                        }
                    }
                }
            }
        }
        if ($importer) {
            $lines = @(
                "# Catzc $version root importer (generated by Install-Catzc — do not edit)."
                '# Dot-source it to load catzc from the installed build, with this folder as the working root:  . ./importer.ps1'
                'param([switch] $AllowWarnings)'
                ". (Join-Path `$PSScriptRoot '.vendor/Catzc/$version/Import-Catzc.ps1') -RepositoryRoot `$PSScriptRoot -AllowWarnings:`$AllowWarnings"
            )
            Write-FileIfChanged -Path $importer -Content ($lines -join "`n") | Out-Null

            # The shell entry: install-time absolute paths, single-quoted for POSIX sh, so it is written here and not rendered as a root config.
            $shellQuote = { param([string] $Path) "'$(([System.IO.Path]::GetFullPath($Path) -replace '\\', '/') -replace "'", "'\''")'" }
            $shellLines = @(
                "# Catzc $version root shell importer (generated by Install-Catzc — do not edit)."
                '# Source it to define `cats` from the installed build, with this folder as the working root:  . ./importer.sh'
                '# shellcheck shell=bash'
                "export CATZC_IMPORTER=$(& $shellQuote $importer)"
                "export CATZC_COMMAND_LOOKUP=$(& $shellQuote (Join-Path $moduleTarget '.internal/assets/importer-commands.sh'))"
                '# shellcheck source=/dev/null'
                ". $(& $shellQuote (Join-Path $moduleTarget 'Catzc.Base.RootConfig/assets/root/importer.sh'))"
            )
            Write-FileIfChanged -Path (Join-Path $Root 'importer.sh') -Content ($shellLines -join "`n") | Out-Null
        }
    }

    # The consumer root files are rendered by the installed build's own import, in a child that loads the root through its importer.
    $rootConfigs = @()
    if ($importer -and -not $DryRun) {
        $importerName = [System.IO.Path]::GetFileName($importer)
        $child = Invoke-Executable "pwsh -NoProfile -NonInteractive -Command `". './$importerName' | Out-Null; & (Get-Module Catzc.Base.RootConfig) { Get-RootConfigTargets -Config (Get-Config -Config rootconfig) -FollowMix -Consumer } | ForEach-Object target`"" `
            -WorkingDirectory $Root -PassThru -NoAssert -Silent
        if ($child.ExitCode -ne 0) {
            throw "Rendering the root files in '$Root' failed with exit code $($child.ExitCode): $($child.Full)"
        }
        # A target is listed once the import has written it; a wildcard target counts when it matches a file.
        $rootConfigs = @($child.Output -split "`r?`n" | Where-Object { $_ -and (Test-Path -Path (Join-Path $Root $_)) })
    }

    if (-not $Silent) {
        $verb = if ($DryRun) {
            'Would install'
        }
        elseif ($copy) {
            'Installed'
        }
        else {
            'Already current:'
        }
        $where = "module $moduleTarget"
        if ($importer) {
            $where += "; importer $importer; shell importer $(Join-Path $Root 'importer.sh')"
        }
        Write-Message "$verb Catzc $version -> $where"
        if ($importer) {
            Write-Message "$(if ($DryRun) { 'Would render' } else { 'Rendered' }) the root files of $Root"
        }
    }

    [pscustomobject]@{
        ModulePath     = $moduleTarget
        Importer       = $importer
        Version        = $version
        ContentHash    = $sourceHash
        AlreadyCurrent = -not $copy
        RootConfigs    = $rootConfigs
        # The build this install copied from, so a caller installs the same build again without naming its folder.
        Source         = $Source
    }
}
