Describe 'Test-WorldMap' -Tag 'L0', 'logic' {
    BeforeAll {
        # Each row: path, track, file language, stack violation; every file is live.
        $newMap = {
            param([object[]] $Rows)
            $placements = @(foreach ($row in $Rows) {
                    [Catzc.Base.Maps.MapPlacement]::new($row[0], $row[1], $row[2], $true, $row[3], 'none', $null, [string[]] @())
                })
            [Catzc.Base.Maps.WorldMap]::new(@('gadgets', 'widgets'), @('gadget-text', 'widget-script'), $placements, $null)
        }

        $noTrack = [Catzc.Base.Maps.WorldMap]::NoTrack
        $noFileLanguage = [Catzc.Base.Maps.WorldMap]::NoFileLanguage
        $script:cleanMap = & $newMap -Rows @(
            , @('widgets/Alpha/Get-Widget.ps1', 'widgets', 'widget-script', $false)
            , @('gadgets/gadget.txt', 'gadgets', 'gadget-text', $false)
            , @('importer.ps1', $noTrack, 'widget-script', $false)
            , @('out/.gitkeep', $noTrack, $noFileLanguage, $false)
        )
        $script:brokenMap = & $newMap -Rows @(
            , @('widgets/Alpha/Get-Widget.ps1', 'widgets', 'widget-script', $false)
            , @('widgets/Alpha/b.txt', 'widgets', 'gadget-text', $true)
            , @('widgets/Alpha/a.txt', 'widgets', 'gadget-text', $true)
            , @('sprockets/one.ps1', $noTrack, 'widget-script', $false)
            , @('sprockets/two.ps1', $noTrack, 'widget-script', $false)
            , @('cogs/README', $noTrack, $noFileLanguage, $false)
            , @('out/.gitkeep', $noTrack, $noFileLanguage, $false)
        )
        $script:fullGlossary = @(foreach ($term in 'track', 'file language', 'widget', 'gadget box') {
                [pscustomobject]@{ Concept = [pscustomobject]@{ term = $term } }
            })
    }

    BeforeEach {
        Mock Write-Message -ModuleName Catzc.Base.Reports { }
        $script:map = $script:cleanMap
        $script:glossary = $script:fullGlossary
        $script:labels = [pscustomobject]@{ row_axis = 'Widgets'; column_axis = 'Gadget box: the columns' }
        Mock Get-WorldMap -ModuleName Catzc.Base.Maps { $script:map }
        Mock Get-Glossary -ModuleName Catzc.Base.Maps { , $script:glossary }
        Mock Get-Config -ModuleName Catzc.Base.Maps -ParameterFilter { $Config -eq 'maps' } { [pscustomobject]@{ labels = $script:labels } }
        $script:out = Join-Path $TestDrive ([guid]::NewGuid().ToString('n'))
    }

    It 'passes a clean map, and reports its facts' -Tag 'ADR-AUTO-TEST-QUALITYGATE' {
        { Test-WorldMap -OutputFolder $script:out } | Should -Not -Throw
        $result = Test-WorldMap -OutputFolder $script:out -PassThru
        $result.Subject | Should -Be 'world-map'
        $result.IssueCount | Should -Be 0
        $result.Facts['Files'] | Should -Be 4
        $result.Facts['Tracks'] | Should -Be 2
        $result.Facts['FileLanguages'] | Should -Be 2
        $result.Facts['StackViolations'] | Should -Be 0
        $result.Facts['Labels'] | Should -Be 2
    }

    It 'reports one issue per stack-violation cell, naming its count and its first file' -Tag 'DDR-TRACK-ONETECHSTACK' {
        $script:map = $script:brokenMap
        $result = Test-WorldMap -OutputFolder $script:out -PassThru
        $result.Facts['StackViolations'] | Should -Be 2
        $result.Issues | Should -Contain "stack violation: widgets x gadget-text holds 2 live file(s) outside the track's file languages, e.g. widgets/Alpha/a.txt (DDR-TRACK-ONETECHSTACK)"
    }

    It 'reports each root folder no track names, never out/ or a file at the root' -Tag 'DDR-TRACK-TRACKISPLACEDCLUSTER' {
        $script:map = $script:brokenMap
        $issues = @((Test-WorldMap -OutputFolder $script:out -PassThru).Issues | Where-Object { $_ -like 'undeclared root folder:*' })
        $issues | Should -Be @(
            'undeclared root folder: cogs/ holds 1 tracked file(s) but no track names it (DDR-TRACK-TRACKISPLACEDCLUSTER)'
            'undeclared root folder: sprockets/ holds 2 tracked file(s) but no track names it (DDR-TRACK-TRACKISPLACEDCLUSTER)'
        )
    }

    It 'reports a maps.yml label whose head names no glossary term, leaving the value_chain_ labels to Test-ValueChainMap' -Tag 'DDR-TRACK-LABELSNAMEDEFINEDTERMS' {
        $script:labels = [pscustomobject]@{
            row_axis          = 'Widgets'
            legend_files      = 'Gizmos per widget'
            column_axis       = 'Sprocket: gadget boxes'
            value_chain_title = 'Gizmo map'
        }
        $issues = @((Test-WorldMap -OutputFolder $script:out -PassThru).Issues)
        $issues | Should -Be @(
            "unregistered label: maps.yml labels.column_axis 'Sprocket: gadget boxes' names no glossary term in its head (DDR-TRACK-LABELSNAMEDEFINEDTERMS)"
            "unregistered label: maps.yml labels.legend_files 'Gizmos per widget' names no glossary term in its head (DDR-TRACK-LABELSNAMEDEFINEDTERMS)"
        )
    }

    It 'reports the track and file-language names when the glossary lacks their axis term' -Tag 'DDR-TRACK-LABELSNAMEDEFINEDTERMS' {
        $script:glossary = @($script:fullGlossary | Where-Object { $_.Concept.term -in 'widget', 'gadget box' })
        $issues = @((Test-WorldMap -OutputFolder $script:out -PassThru).Issues)
        $issues | Should -Be @(
            "unregistered label: the names gadgets, widgets print as instances of 'track', which the glossary does not hold (DDR-TRACK-TRACKISPLACEDCLUSTER)"
            "unregistered label: the names gadget-text, widget-script print as instances of 'file language', which the glossary does not hold (DDR-TRACK-FILELANGUAGE)"
        )
    }

    It 'throws once listing every issue without -PassThru' -Tag 'ADR-AUTO-TEST-QUALITYGATE' {
        $script:map = $script:brokenMap
        $thrown = { Test-WorldMap -OutputFolder $script:out } | Should -Throw -PassThru
        $thrown.Exception.Message | Should -BeLike 'Test-WorldMap failed: 3 issue(s)*'
        $thrown.Exception.Message | Should -BeLike '*undeclared root folder: sprockets/*'
    }

    It 'writes the report to its folder and points latest.txt at it' -Tag 'ADR-AUTO-TEST-QUALITYGATE' {
        $result = Test-WorldMap -OutputFolder $script:out -PassThru
        Test-Path -LiteralPath (Join-Path $result.ReportPath 'world-map.md') | Should -BeTrue
        (Get-Content -LiteralPath (Join-Path $script:out 'latest.txt') -Raw).Trim() | Should -Be (Split-Path $result.ReportPath -Leaf)
    }
}

Describe 'Test-WorldMap on the repository' -Tag 'L1', 'integrity', 'source-only' {
    It 'Test-WorldMap passes over the repository' -Tag 'DDR-TRACK-TRACKISPLACEDCLUSTER', 'DDR-TRACK-ONETECHSTACK', 'DDR-TRACK-LABELSNAMEDEFINEDTERMS', 'ADR-AUTO-TEST-QUALITYGATE' {
        $result = Test-WorldMap -PassThru -OutputFolder (Join-Path $TestDrive 'world-map')
        $result.IssueCount | Should -Be 0 -Because ($result.Issues -join "`n")
    }
}
