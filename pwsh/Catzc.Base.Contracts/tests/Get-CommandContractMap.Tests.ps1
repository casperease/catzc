Describe 'Get-CommandContractMap' -Tag 'L0', 'logic', 'ADR-REPO-CMDCONTRACT-ONEREADER' {
    BeforeEach {
        Mock Get-CommandContract -ModuleName Catzc.Base.Contracts {
            [pscustomobject]@{ Name = 'get_widget'; Signature = 'get_widget(path)' }
            [pscustomobject]@{ Name = 'test_gadget'; Signature = 'test_gadget()' }
        }
    }

    It 'keys every command contract by its name, read once through the one reader' {
        $map = InModuleScope Catzc.Base.Contracts { Get-CommandContractMap -RepositoryRoot 'widget-root' }
        $map.Keys | Sort-Object | Should -Be @('get_widget', 'test_gadget')
        $map['get_widget'].Signature | Should -Be 'get_widget(path)'
        Should -Invoke Get-CommandContract -ModuleName Catzc.Base.Contracts -Times 1 -Exactly -ParameterFilter { $RepositoryRoot -eq 'widget-root' }
    }

    It 'gives an empty table when no command is contracted' {
        Mock Get-CommandContract -ModuleName Catzc.Base.Contracts { }
        $map = InModuleScope Catzc.Base.Contracts { Get-CommandContractMap -RepositoryRoot 'widget-root' }
        $map | Should -BeOfType [hashtable]
        $map.Count | Should -Be 0
    }
}
