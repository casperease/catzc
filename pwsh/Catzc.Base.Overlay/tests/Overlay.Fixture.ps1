$script:fixtureRoot = Join-Path $TestDrive ([guid]::NewGuid().ToString('N'))
$script:modulesRoot = Join-Path $fixtureRoot 'bundle'
$script:overlayRoot = Join-Path $fixtureRoot 'consumer/.catzc/pwsh'
