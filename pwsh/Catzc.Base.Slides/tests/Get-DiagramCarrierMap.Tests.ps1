Describe 'Get-DiagramCarrierMap' -Tag 'L0', 'logic', 'ADR-REPO-SLIDES-DECLARATION' {
    BeforeAll {
        $script:root = Join-Path $TestDrive ([guid]::NewGuid().ToString('N'))
        [System.IO.Directory]::CreateDirectory((Join-Path $script:root 'kit/configs')) | Out-Null
        $script:config = Join-Path $script:root 'kit/configs/drawio.yml'
    }

    It 'reads the default carrier and the carrier each named stem takes' {
        [System.IO.File]::WriteAllText($script:config, "renderer:`n  carrier: file`ncarriers:`n  docs/widgets/.assets/widget-flow: article`n")
        $map = InModuleScope Catzc.Base.Slides -Parameters @{ Root = $script:root } { param($Root) Get-DiagramCarrierMap -RepositoryRoot $Root -Kit kit }
        $map.Default | Should -BeExactly 'file'
        $map.Carriers['docs/widgets/.assets/widget-flow'] | Should -BeExactly 'article'
    }

    It 'gives an empty map when no diagram is named' {
        [System.IO.File]::WriteAllText($script:config, "renderer:`n  carrier: file`ncarriers:`n")
        $map = InModuleScope Catzc.Base.Slides -Parameters @{ Root = $script:root } { param($Root) Get-DiagramCarrierMap -RepositoryRoot $Root -Kit kit }
        $map.Carriers.Count | Should -Be 0
    }

    It 'stops when the kit declares no default carrier' {
        [System.IO.File]::WriteAllText($script:config, "renderer:`n  page: dark`n")
        { InModuleScope Catzc.Base.Slides -Parameters @{ Root = $script:root } { param($Root) Get-DiagramCarrierMap -RepositoryRoot $Root -Kit kit } } |
            Should -Throw '*declares no renderer.carrier*'
    }
}
