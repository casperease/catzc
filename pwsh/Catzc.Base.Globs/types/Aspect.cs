using System;
using System.Collections.Generic;
using System.Text.RegularExpressions;

namespace Catzc.Base.Globs;

public sealed class Aspect
{
    public override string ToString() => Catzc.Base.Objects.ConsoleText.ToConsoleString(this);

    private static readonly Regex KebabCase = new Regex("^[a-z][a-z0-9]*(-[a-z0-9]+)*$");

    public string Name { get; }
    public IReadOnlyList<string> Patterns { get; }   // relative to the unit root

    public Aspect(string name, string[] patterns)
    {
        if (string.IsNullOrWhiteSpace(name) || !KebabCase.IsMatch(name))
        {
            throw new ArgumentException(string.Format("aspect name '{0}' must be kebab-case", name));
        }
        if (patterns == null || patterns.Length == 0)
        {
            throw new ArgumentException(string.Format("aspect '{0}' needs at least one pattern", name));
        }
        Name = name;
        Patterns = (string[])patterns.Clone();
    }
}

public sealed class CompiledAspect
{
    public string Name { get; }
    public string[] Include { get; }
    public string[] Exclude { get; }

    public CompiledAspect(string name, string[] include, string[] exclude)
    {
        Name = name;
        Include = include;
        Exclude = exclude;
    }
}

public static class AspectPartition
{
    public static IReadOnlyList<CompiledAspect> Compile(IReadOnlyList<Aspect> aspects, string unitRoot)
    {
        if (aspects == null || aspects.Count == 0)
        {
            throw new ArgumentException("an aspect partition needs at least one aspect");
        }
        string root = (unitRoot ?? string.Empty).TrimEnd('/');
        List<CompiledAspect> compiled = new List<CompiledAspect>();
        List<string> earlier = new List<string>();
        foreach (Aspect aspect in aspects)
        {
            List<string> include = new List<string>();
            foreach (string pattern in aspect.Patterns) { include.Add(Prefix(root, pattern)); }
            compiled.Add(new CompiledAspect(aspect.Name, include.ToArray(), earlier.ToArray()));
            earlier.AddRange(include);
        }
        return compiled;
    }

    private static string Prefix(string root, string pattern)
    {
        return root.Length == 0 ? pattern : root + "/" + pattern;
    }

    public static IReadOnlyList<string> Validate(IReadOnlyList<GlobSet> aspectSets, IEnumerable<string> universe)
    {
        List<string> violations = new List<string>();
        foreach (string file in universe)
        {
            List<string> owners = new List<string>();
            foreach (GlobSet set in aspectSets)
            {
                if (set.Matches(file)) { owners.Add(set.Name); }
            }
            if (owners.Count == 0)
            {
                violations.Add(string.Format("'{0}' is claimed by no aspect (exhaustive violated)", file));
            }
            else if (owners.Count > 1)
            {
                violations.Add(string.Format("'{0}' is claimed by {1} aspects: {2} (disjoint violated)", file, owners.Count, string.Join(", ", owners)));
            }
        }
        return violations;
    }

    // Per aspect, the fewest paths that cover exactly that aspect's files among the given ones: a file's topmost folder whose every given
    // file is in the aspect, or the file itself. A file no set claims lies in no cover; the first aspect whose set claims a file wins.
    public static IReadOnlyDictionary<string, string[]> Cover(IReadOnlyDictionary<string, IReadOnlyList<GlobSet>> aspectSets, IReadOnlyList<string> files)
    {
        if (aspectSets == null) { throw new ArgumentNullException(nameof(aspectSets)); }
        if (files == null) { throw new ArgumentNullException(nameof(files)); }
        Dictionary<string, int> total = new Dictionary<string, int>(StringComparer.Ordinal);
        Dictionary<string, int> held = new Dictionary<string, int>(StringComparer.Ordinal);
        Dictionary<string, string> aspectOf = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string file in files)
        {
            foreach (KeyValuePair<string, IReadOnlyList<GlobSet>> aspect in aspectSets)
            {
                bool claimed = false;
                foreach (GlobSet set in aspect.Value) { if (set.Matches(file)) { claimed = true; break; } }
                if (claimed) { aspectOf[file] = aspect.Key; break; }
            }
            aspectOf.TryGetValue(file, out string name);
            for (string folder = Parent(file); folder != null; folder = Parent(folder))
            {
                total[folder] = total.TryGetValue(folder, out int count) ? count + 1 : 1;
                if (name != null)
                {
                    string key = name + "|" + folder;
                    held[key] = held.TryGetValue(key, out int heldCount) ? heldCount + 1 : 1;
                }
            }
        }
        Dictionary<string, string[]> cover = new Dictionary<string, string[]>(StringComparer.Ordinal);
        foreach (string name in aspectSets.Keys)
        {
            SortedSet<string> paths = new SortedSet<string>(StringComparer.Ordinal);
            foreach (string file in files)
            {
                if (!aspectOf.TryGetValue(file, out string owner) || owner != name) { continue; }
                string top = file;
                for (string folder = Parent(file); folder != null; folder = Parent(folder))
                {
                    if (!held.TryGetValue(name + "|" + folder, out int heldCount) || heldCount != total[folder]) { break; }
                    top = folder;
                }
                paths.Add(top);
            }
            string[] list = new string[paths.Count];
            paths.CopyTo(list);
            cover[name] = list;
        }
        return cover;
    }

    private static string Parent(string path)
    {
        int cut = path.LastIndexOf('/');
        return cut > 0 ? path.Substring(0, cut) : null;
    }
}
