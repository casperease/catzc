using System;
using System.Management.Automation;

namespace Catzc.Base.Globs;

public sealed class GlobPattern
{
    // The pattern as authored.
    public string Pattern { get; }

    // Per segment: the compiled per-segment matcher, or null where the segment is the '**' operator.
    private readonly WildcardPattern[] segments;
    private readonly bool[] isAnyDepth;

    public GlobPattern(string pattern)
    {
        if (string.IsNullOrWhiteSpace(pattern))
        {
            throw new ArgumentException("a glob pattern must be non-empty");
        }
        if (pattern.IndexOf('\\') >= 0)
        {
            throw new ArgumentException(string.Format("glob pattern '{0}': the separator is '/', never '\\' (FDR-CD-GLOBS-MALFORMEDPATTERNREJECTED)", pattern));
        }
        if (pattern.IndexOf('`') >= 0)
        {
            throw new ArgumentException(string.Format("glob pattern '{0}': the dialect has no escape character — a backtick is rejected (FDR-CD-GLOBS-MALFORMEDPATTERNREJECTED)", pattern));
        }
        if (pattern[0] == '/')
        {
            throw new ArgumentException(string.Format("glob pattern '{0}': patterns are repo-relative — no leading '/' (FDR-CD-GLOBS-MALFORMEDPATTERNREJECTED)", pattern));
        }

        string[] parts = pattern.Split('/');
        WildcardPattern[] compiled = new WildcardPattern[parts.Length];
        bool[] anyDepth = new bool[parts.Length];

        for (int i = 0; i < parts.Length; i++)
        {
            string segment = parts[i];
            if (segment.Length == 0)
            {
                throw new ArgumentException(string.Format("glob pattern '{0}': empty segment (a trailing or doubled '/') (FDR-CD-GLOBS-MALFORMEDPATTERNREJECTED)", pattern));
            }
            if (segment == "." || segment == "..")
            {
                throw new ArgumentException(string.Format("glob pattern '{0}': '.'/'..' segments are rejected (FDR-CD-GLOBS-MALFORMEDPATTERNREJECTED)", pattern));
            }
            if (segment == "**")
            {
                anyDepth[i] = true;
                continue;
            }
            if (segment.Contains("**"))
            {
                throw new ArgumentException(string.Format("glob pattern '{0}': '**' must stand as a whole segment, never inside one (FDR-CD-GLOBS-REPOSITORYRELATIVEPATTERNS)", pattern));
            }

            WildcardPattern wildcard = WildcardPattern.Get(segment, WildcardOptions.None);
            try
            {
                wildcard.IsMatch(string.Empty);
            }
            catch (WildcardPatternException ex)
            {
                throw new ArgumentException(string.Format("glob pattern '{0}': segment '{1}' is not a valid wildcard: {2}", pattern, segment, ex.Message));
            }
            compiled[i] = wildcard;
        }

        Pattern = pattern;
        segments = compiled;
        isAnyDepth = anyDepth;
        int literal = 0;
        while (literal < parts.Length - 1 && !anyDepth[literal] && !WildcardPattern.ContainsWildcardCharacters(parts[literal]))
        {
            literal++;
        }
        LiteralPrefix = literal == 0 ? string.Empty : string.Join("/", parts, 0, literal) + "/";
    }

    // The folder path before the first wildcard segment, '/'-terminated, or empty: every path the pattern matches starts with it.
    public string LiteralPrefix { get; }

    // The paths, in their order, that at least one of the patterns matches; each pattern is tried only on the paths under its literal
    // prefix, so a list of many paths is matched in one call.
    public static string[] MatchingPaths(string[] patterns, string[] repoRelativePaths)
    {
        GlobPattern[] compiled = new GlobPattern[patterns?.Length ?? 0];
        for (int i = 0; i < compiled.Length; i++)
        {
            compiled[i] = new GlobPattern(patterns[i]);
        }
        System.Collections.Generic.List<string> kept = new System.Collections.Generic.List<string>();
        foreach (string path in repoRelativePaths ?? new string[0])
        {
            if (string.IsNullOrEmpty(path)) { continue; }
            foreach (GlobPattern glob in compiled)
            {
                if (path.StartsWith(glob.LiteralPrefix, StringComparison.Ordinal) && glob.Matches(path))
                {
                    kept.Add(path);
                    break;
                }
            }
        }
        return kept.ToArray();
    }

    // True when the repo-relative, '/'-separated path matches. A null/empty path matches nothing.
    public bool Matches(string repoRelativePath)
    {
        if (string.IsNullOrEmpty(repoRelativePath)) { return false; }
        return MatchFrom(0, repoRelativePath.Split('/'), 0);
    }

    private bool MatchFrom(int patternIndex, string[] path, int pathIndex)
    {
        while (patternIndex < segments.Length)
        {
            if (isAnyDepth[patternIndex])
            {
                if (patternIndex == segments.Length - 1) { return true; }
                for (int consumeTo = pathIndex; consumeTo <= path.Length; consumeTo++)
                {
                    if (MatchFrom(patternIndex + 1, path, consumeTo)) { return true; }
                }
                return false;
            }
            if (pathIndex >= path.Length) { return false; }
            if (!segments[patternIndex].IsMatch(path[pathIndex])) { return false; }
            patternIndex++;
            pathIndex++;
        }
        return pathIndex == path.Length;
    }

    public override string ToString()
    {
        return Pattern;
    }
}
