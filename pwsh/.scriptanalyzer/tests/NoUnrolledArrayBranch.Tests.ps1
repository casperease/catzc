Describe 'Measure-NoUnrolledArrayBranch' -Tag 'L0', 'logic', 'ADR-PWSH-ERROR-STRICTCLEAN' {
    BeforeAll {
        Import-Module (Join-Path (Get-CatzcModulesRoot) '.scriptanalyzer/NoUnrolledArrayBranch.psm1') -Force
        # The rule's return type ([DiagnosticRecord]) lives in the PSScriptAnalyzer assembly.
        if (-not (Get-Module PSScriptAnalyzer)) {
            Import-Module (Join-Path (Get-CatzcModulesRoot) '.vendor/PSScriptAnalyzer') -Force
        }

        function Test-UnrolledBranch {
            param([string] $Code)
            $ast = [System.Management.Automation.Language.Parser]::ParseInput($Code, [ref]$null, [ref]$null)
            Measure-NoUnrolledArrayBranch -ScriptBlockAst $ast
        }
    }

    It 'flags an assigned if whose branch yields a bare array: <Code>' -ForEach @(
        @{ Code = '$widgets = if ($ready) { @(Get-Widget) }' }
        @{ Code = '$widgets = if ($ready) { @(Get-Widget) } else { @() }' }
        @{ Code = '$widgets = if ($ready) { 1 } elseif ($gadget) { @($gadget) } else { 2 }' }
    ) {
        $records = @(Test-UnrolledBranch $Code)
        $records | Should -HaveCount 1
        $records[0].RuleName | Should -Be 'Measure-NoUnrolledArrayBranch'
    }

    It 'flags a nested occurrence once' {
        @(Test-UnrolledBranch 'function Get-Gadget { foreach ($item in $items) { $keys = if ($item) { @($item.Keys) } } }') | Should -HaveCount 1
    }

    It 'accepts a branch that cannot unroll an array: <Code>' -ForEach @(
        @{ Code = '$widgets = @(if ($ready) { Get-Widget })' }                  # the sanctioned form: the statement is wrapped
        @{ Code = '$widgets = if ($ready) { Get-Widget }' }                     # no array expression in the branch
        @{ Code = '$widgets = if ($ready) { $x = @(Get-Widget); $x.Count }' }   # the array is assigned, not yielded
        @{ Code = 'if ($ready) { @(Get-Widget) }' }                             # not assigned: it writes to the caller's pipeline
        @{ Code = '$widgets = switch ($ready) { 1 { @(Get-Widget) } }' }        # only an if statement is in scope
    ) {
        Test-UnrolledBranch $Code | Should -BeNullOrEmpty
    }
}
