Describe 'Get-RootConfigInputStamp' -Tag 'L0', 'logic', 'ADR-AUTO-CACHE-CHECKEDFILESACROSSSESSIONS' {
    BeforeAll {
        Import-InternalModule TestKit

        $script:fake = New-FakeRepositoryRoot -Files @{
            'sources/widget.yml'       = "alpha: 1`n"
            'widgets/alpha/gadget.txt' = "alpha`n"
            'gadget.txt'               = "rendered`n"
            'copied.yml'               = "alpha: 1`n"
        }
        $script:entries = @(
            [pscustomobject]@{ target = 'gadget.txt'; source = $null; sources = @('sources/widget.yml'); generator = 'New-Widget' }
            [pscustomobject]@{ target = 'widgets/*/gadget.txt'; source = $null; sources = @('sources/widget.yml'); generator = 'New-Widget' }
            [pscustomobject]@{ target = 'copied.yml'; source = 'sources/widget.yml'; sources = @(); generator = $null }
        )

        function script:Get-Stamp {
            InModuleScope Catzc.Base.RootConfig -Parameters @{ Entries = $script:entries } {
                param($Entries)
                Get-RootConfigInputStamp -Entries $Entries
            }
        }
    }

    AfterAll {
        Remove-FakeRepositoryRoot $script:fake
    }

    It 'is the same hash twice over an unchanged tree' {
        $first = Get-Stamp
        $first | Should -Match '^[0-9a-f]{64}$'
        Get-Stamp | Should -Be $first
    }

    It 'changes when a declared source changes' {
        $before = Get-Stamp
        [System.IO.File]::WriteAllText((Join-Path $script:fake.Root 'sources/widget.yml'), "alpha: 2`n")
        Get-Stamp | Should -Not -Be $before
    }

    It 'changes when a rendered target is edited, and when it goes missing' {
        $before = Get-Stamp
        [System.IO.File]::AppendAllText((Join-Path $script:fake.Root 'gadget.txt'), "edited`n")
        $edited = Get-Stamp
        $edited | Should -Not -Be $before
        [System.IO.File]::Delete((Join-Path $script:fake.Root 'gadget.txt'))
        Get-Stamp | Should -Not -Be $edited
    }

    It 'changes when the generated-file head''s key list changes, which every root file carries' -Tag 'ADR-REPO-FILEMETA-COMPOSEDFILES' {
        $script:languagesBase = Join-Path $script:fake.Root 'languages-module'
        [System.IO.Directory]::CreateDirectory((Join-Path $script:languagesBase 'configs')) | Out-Null
        [System.IO.File]::WriteAllText((Join-Path $script:languagesBase 'configs/generated-head.yml'), "keys:`n  - with_body_sha`n  - warning`n")
        Mock Get-Module -ModuleName Catzc.Base.RootConfig -ParameterFilter { $Name -eq 'Catzc.Base.Languages' } { [pscustomobject]@{ ModuleBase = $script:languagesBase } }
        $before = Get-Stamp
        [System.IO.File]::WriteAllText((Join-Path $script:languagesBase 'configs/generated-head.yml'), "keys:`n  - warning`n  - with_body_sha`n")
        Get-Stamp | Should -Not -Be $before
    }

    It 'changes when a folder appears that a wildcard entry would render into' {
        $before = Get-Stamp
        [System.IO.Directory]::CreateDirectory((Join-Path $script:fake.Root 'widgets/beta')) | Out-Null
        Get-Stamp | Should -Not -Be $before
    }

    It 'changes when a copy is edited by hand, so the next run rewrites it' {
        $before = Get-Stamp
        $copy = Join-Path $script:fake.Root 'copied.yml'
        try {
            [System.IO.File]::WriteAllText($copy, "edited by hand`n")
            Get-Stamp | Should -Not -Be $before
        }
        finally {
            [System.IO.File]::WriteAllText($copy, "alpha: 1`n")
        }
    }
}
