Describe 'RootConfigFiles' -Tag 'L0', 'logic' {
    It 'constructs and exposes valid entries in registry order' {
        $c = [Catzc.Base.RootConfig.RootConfigFiles]::new(@{
                files = @(
                    @{ target = 'a.yml'; source = 's/a.yml'; optIn = $true }
                    @{ target = 'importer.ps1'; generator = 'New-Importer'; committed = $true }
                )
            })
        @($c.files).Count | Should -Be 2
        $c.files[0].target | Should -Be 'a.yml'
        $c.files[1].generator | Should -Be 'New-Importer'
    }

    It 'throws when files is missing' {
        { [Catzc.Base.RootConfig.RootConfigFiles]::new(@{}) } | Should -Throw "*'files' must be a list*"
    }

    It 'throws when files is empty' {
        { [Catzc.Base.RootConfig.RootConfigFiles]::new(@{ files = @() }) } | Should -Throw "*'files' must be a list*"
    }

    It 'throws on a duplicate target (case-insensitive)' {
        { [Catzc.Base.RootConfig.RootConfigFiles]::new(@{
                    files = @(
                        @{ target = 'a.yml'; source = 's1' }
                        @{ target = 'A.YML'; source = 's2' }
                    )
                }) } | Should -Throw '*duplicate target*'
    }

    It 'collects every malformed entry into one error' {
        $construct = {
            [Catzc.Base.RootConfig.RootConfigFiles]::new(@{
                    files = @(
                        @{ source = 'no-target' }
                        @{ target = 'both'; source = 's'; generator = 'g' }
                    )
                })
        }
        $construct | Should -Throw '*target is required*'
        $construct | Should -Throw '*exactly one*'
    }

    It 'rejects an unknown top-level key' {
        { [Catzc.Base.RootConfig.RootConfigFiles]::new(@{ widget = 1 }) } | Should -Throw "*unknown top-level key 'widget'*"
    }
}

Describe 'RootConfigFiles.GeneratorInputs' -Tag 'L0', 'logic', 'ADR-AUTO-CACHE-CHECKEDFILESACROSSSESSIONS' {
    It 'names the four generator modules and the head writer''s files under the modules root, sorted, existing or not' {
        $root = Join-Path $TestDrive 'widget-modules'
        $inputs = [Catzc.Base.RootConfig.RootConfigFiles]::GeneratorInputs($root)
        $relative = @($inputs | ForEach-Object { [System.IO.Path]::GetRelativePath($root, $_).Replace('\', '/') })
        $relative | Should -Be @(
            'Catzc.Base.Contracts'
            'Catzc.Base.Git'
            'Catzc.Base.Languages/Format-GeneratedFileHead.ps1'
            'Catzc.Base.Languages/New-GoWorkspace.ps1'
            'Catzc.Base.Languages/New-PythonProject.ps1'
            'Catzc.Base.Languages/configs/generated-head.yml'
            'Catzc.Base.RootConfig'
            'Catzc.Base.VSCode'
        )
    }

    It 'refuses an empty modules root' {
        { [Catzc.Base.RootConfig.RootConfigFiles]::GeneratorInputs('') } | Should -Throw '*modulesRoot*'
    }
}

Describe 'RootConfigFiles tool settings' -Tag 'L0', 'logic' {
    It 'names cspell.yml and .markdownlint.yml at the repository root, and refuses an empty root' {
        $root = Join-Path $TestDrive 'widget-repository'
        [Catzc.Base.RootConfig.RootConfigFiles]::SpellingConfigPath($root) | Should -Be ([System.IO.Path]::GetFullPath((Join-Path $root 'cspell.yml')))
        [Catzc.Base.RootConfig.RootConfigFiles]::MarkdownlintConfigPath($root) | Should -Be ([System.IO.Path]::GetFullPath((Join-Path $root '.markdownlint.yml')))
        { [Catzc.Base.RootConfig.RootConfigFiles]::SpellingConfigPath('') } | Should -Throw '*repositoryRoot*'
    }
}
