function New-CatsCommandLookup {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [string] $RepositoryRoot = (Get-RepositoryRoot)
    )

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('# shellcheck shell=bash')
    $lines.Add('# The command lookup `cats` reads before it starts pwsh (ADR-REPO-CMDCONTRACT#5): one line per contracted parameter of')
    $lines.Add('# contracts/catzc/0.0.0, tab-separated: command, parameter, type, list (1 or 0), mandatory (1 or 0), pipeline (1 or 0), asset. A')
    $lines.Add('# command with no parameter has one line with an empty parameter. Generated by New-CatsCommandLookup through Build-RootConfig.')
    $lines.Add("_catzc_commands='")
    $contracts = @(Get-CommandContract -RepositoryRoot $RepositoryRoot | Sort-Object -Property Name -Culture ([System.Globalization.CultureInfo]::InvariantCulture))
    foreach ($contract in $contracts) {
        $asset = "contracts/$($contract.Asset.Unit)/$($contract.Asset.Version)/$($contract.Asset.AssetPath)"
        $parameters = @($contract.parameters)
        if ($parameters.Count -eq 0) {
            $lines.Add(($contract.Name, '', '', '0', '0', '0', $asset) -join "`t")
            continue
        }
        foreach ($parameter in $parameters) {
            $lines.Add(($contract.Name, $parameter.Name, $parameter.Type, [int] $parameter.IsList, [int] $parameter.Mandatory, [int] $parameter.Pipeline, $asset) -join "`t")
        }
    }
    $lines.Add("'")
    ($lines -join "`n") + "`n"
}
