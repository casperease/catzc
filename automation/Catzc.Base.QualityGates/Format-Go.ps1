<#
.SYNOPSIS
    Formats the repository's Go test files with gofmt.
.DESCRIPTION
    Runs the managed toolchain's gofmt over every Go test module (Get-LanguageTestFolders, language go: <goRoot>/tests/<module>/,
    [ADR-AUTO-GO#8](/docs/adr/automation/go/test-artifacts.md#rule-adr-auto-go8)): `gofmt -l` lists the files whose
    formatting differs, then `gofmt -w` rewrites exactly those, unless -DryRun. gofmt is the one Go formatter, with
    no options to configure, so a formatted file is the same on every machine.

    gofmt is the gofmt binary beside the managed go (Resolve-ToolExecutable, the tools.yml `go` entry): it throws
    with "Run Install-Go" when no go at the pin is found. A repository without Go test modules has nothing to
    format and needs no go. A file gofmt cannot parse throws with gofmt's message.

    A source-tree tool: it rewrites the repository's Go files, so it throws in build mode (Assert-SourceTree).
.PARAMETER Path
    Folders or .go files to format. Defaults to every Go test module. Any other file throws: go.mod and go.work are
    generated (New-GoWorkspace), not formatted.
.PARAMETER DryRun
    Report which files would change without writing them (the returned list is the same either way).
.PARAMETER PassThru
    Return a result object ({ ChangedCount, ChangedFiles, DryRun }) instead of the list of files.
.OUTPUTS
    [string[]] The full paths of the files that changed (or, under -DryRun, would change).
.EXAMPLE
    Format-Go
.EXAMPLE
    Format-Go -DryRun
#>
function Format-Go {
    [CmdletBinding()]
    [OutputType([string[]])]
    param(
        [string[]] $Path,

        [switch] $DryRun,

        [switch] $PassThru
    )

    Assert-SourceTree

    $targets = @(if ($Path) {
            foreach ($item in $Path) {
                $full = (Resolve-Path -LiteralPath $item).ProviderPath
                # gofmt reads .go files only; go.mod, go.work and go.sum are generated by New-GoWorkspace and go itself.
                if ((Test-Path -LiteralPath $full -PathType Leaf) -and [System.IO.Path]::GetExtension($full) -ne '.go') {
                    throw "Format-Go formats .go files and folders of them; '$item' is not a .go file (go.mod and go.work are generated — run Build-RootConfig)."
                }
                $full
            }
        }
        else {
            foreach ($testFolder in @(Get-LanguageTestFolders)) {
                if ($testFolder.Language -eq 'go') {
                    $testFolder.Folder
                }
            }
        })

    $changed = [System.Collections.Generic.List[string]]::new()
    if ($targets.Count -gt 0) {
        $go = Resolve-ToolExecutable -Tool go
        if (-not ($go.Found -and $go.VersionOk)) {
            throw "Format-Go needs the managed go at the tools.yml pin '$($go.Required)' (found: $($go.Version ?? 'none')). Run Install-Go."
        }
        $gofmt = Join-Path ([System.IO.Path]::GetDirectoryName($go.Path)) ($IsWindows ? 'gofmt.exe' : 'gofmt')
        Assert-PathExist $gofmt -PathType Leaf

        $quoted = ($targets | ForEach-Object { "`"$_`"" }) -join ' '
        $list = Invoke-Executable "`"$gofmt`" -l $quoted" -PassThru -NoAssert -Silent
        if ($list.ExitCode -ne 0) {
            throw "gofmt could not read the Go files (exit $($list.ExitCode)):`n$($list.Full)"
        }
        foreach ($line in ($list.Output -split '\r?\n')) {
            if ($line.Trim()) {
                $changed.Add([System.IO.Path]::GetFullPath($line.Trim()))
            }
        }

        if ($changed.Count -gt 0 -and -not $DryRun) {
            $files = ($changed | ForEach-Object { "`"$_`"" }) -join ' '
            Invoke-Executable "`"$gofmt`" -w $files" -Silent
        }
    }

    $verb = $DryRun ? 'would format' : 'formatted'
    Write-Message "$verb $($changed.Count) Go file(s) across $($targets.Count) path(s)"

    if ($PassThru) {
        return [pscustomobject]@{
            ChangedCount = $changed.Count
            ChangedFiles = $changed.ToArray()
            DryRun       = [bool]$DryRun
        }
    }
    $changed.ToArray()
}
