using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace Catzc.Base.QualityGates;

public sealed class CommentsConfig
{
    public override string ToString() => Catzc.Base.Objects.ConsoleText.ToConsoleString(this);

    static readonly string[] AllowedKeys = { "languages", "min_lines", "keep", "keep_run", "pages", "exclude", "view" };

    public static readonly IReadOnlyDictionary<string, string> DefaultExclude = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["**/tests/**"] = "a test's prose is its own subject",
        ["**/assets/**"] = "an asset is copied or published verbatim elsewhere, where a page of this repository would be foreign",
    };

    public const int DefaultMinLines = 2;
    public const string DefaultView = "out/annotated";
    public static readonly IReadOnlyList<string> DefaultLanguages = new[] { "powershell", "yaml", "pipeline-yaml", "csharp", "bicep" };
    public static readonly IReadOnlyDictionary<string, IReadOnlyList<string>> DefaultKeep = new Dictionary<string, IReadOnlyList<string>>(StringComparer.OrdinalIgnoreCase)
    {
        ["powershell"] = new[] { ".SYNOPSIS", ".EXAMPLE", ".OUTPUTS", ".INPUTS", "#Requires", "#region", "#endregion", "#!", "# cspell:" },
        ["yaml"] = new[] { "# yaml-language-server:", "# cspell:" },
        ["pipeline-yaml"] = new[] { "# yaml-language-server:", "# cspell:" },
        ["csharp"] = new[] { "// <auto-generated", "// cspell:" },
        ["bicep"] = new[] { "// cspell:" },
    };
    public static readonly IReadOnlyList<(string source, string docs)> DefaultPages = new[]
    {
        ("automation/*", "docs/references/automation/{kebab}"),
        ("pipelines", "docs/references/pipelines"),
        ("infrastructure", "docs/references/infrastructure"),
        (".claude/hooks", "docs/references/automation/claude-hooks"),
    };

    public IReadOnlyList<string> languages { get; }
    public int min_lines { get; }
    public IReadOnlyDictionary<string, IReadOnlyList<string>> keep { get; }
    public IReadOnlyDictionary<string, IReadOnlyList<string>> keep_run { get; }
    public IReadOnlyList<CommentPageMap> pages { get; }
    public IReadOnlyDictionary<string, string> exclude { get; }
    public string view { get; }

    readonly List<Catzc.Base.Globs.GlobPattern> excludeGlobs = new List<Catzc.Base.Globs.GlobPattern>();

    public CommentsConfig(IDictionary raw)
    {
        const string name = "comments config";
        languages = DefaultLanguages;
        min_lines = DefaultMinLines;
        var keepLists = new Dictionary<string, IReadOnlyList<string>>(DefaultKeep, StringComparer.OrdinalIgnoreCase);
        var keepRunLists = new Dictionary<string, IReadOnlyList<string>>(StringComparer.OrdinalIgnoreCase);
        var pageMaps = DefaultPages.Select(d => new CommentPageMap(name + ": pages", new Hashtable { ["source"] = d.source, ["docs"] = d.docs })).ToList();
        view = DefaultView;
        var excludeMap = new Dictionary<string, string>(DefaultExclude, StringComparer.Ordinal);

        if (raw != null)
        {
            foreach (object key in raw.Keys)
            {
                string keyName = Convert.ToString(key, CultureInfo.InvariantCulture);
                if (Array.IndexOf(AllowedKeys, keyName) < 0)
                {
                    throw new ArgumentException(string.Format(CultureInfo.InvariantCulture,
                        "{0}: unknown key '{1}' (allowed: {2})", name, keyName, string.Join(", ", AllowedKeys)));
                }
            }

            if (raw.Contains("languages") && raw["languages"] != null)
            {
                languages = Strings(name, "languages", raw["languages"], requireAny: true);
                string duplicate = languages.GroupBy(l => l, StringComparer.OrdinalIgnoreCase).FirstOrDefault(g => g.Count() > 1)?.Key;
                if (duplicate != null)
                {
                    throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: languages lists '{1}' twice", name, duplicate));
                }
            }

            if (raw.Contains("min_lines") && raw["min_lines"] != null)
            {
                if (!int.TryParse(Convert.ToString(raw["min_lines"], CultureInfo.InvariantCulture), NumberStyles.Integer, CultureInfo.InvariantCulture, out int parsed) || parsed <= 0)
                {
                    throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: min_lines must be a positive integer, got '{1}'", name, raw["min_lines"]));
                }
                min_lines = parsed;
            }

            if (raw.Contains("keep") && raw["keep"] != null)
            {
                if (!(raw["keep"] is IDictionary keepRaw))
                {
                    throw new ArgumentException(name + ": keep must be a map of language to a list of comment heads");
                }
                foreach (DictionaryEntry entry in keepRaw)
                {
                    string language = Convert.ToString(entry.Key, CultureInfo.InvariantCulture);
                    if (string.IsNullOrWhiteSpace(language))
                    {
                        throw new ArgumentException(name + ": keep has an empty language key");
                    }
                    keepLists[language] = Strings(name, "keep." + language, entry.Value, requireAny: false);
                }
            }

            if (raw.Contains("keep_run") && raw["keep_run"] != null)
            {
                if (!(raw["keep_run"] is IDictionary keepRunRaw))
                {
                    throw new ArgumentException(name + ": keep_run must be a map of language to a list of comment heads");
                }
                foreach (DictionaryEntry entry in keepRunRaw)
                {
                    string language = Convert.ToString(entry.Key, CultureInfo.InvariantCulture);
                    if (string.IsNullOrWhiteSpace(language))
                    {
                        throw new ArgumentException(name + ": keep_run has an empty language key");
                    }
                    keepRunLists[language] = Strings(name, "keep_run." + language, entry.Value, requireAny: false);
                }
            }

            if (raw.Contains("pages") && raw["pages"] != null)
            {
                if (!(raw["pages"] is IList pagesRaw) || pagesRaw.Count == 0)
                {
                    throw new ArgumentException(name + ": pages must be a non-empty list of { source, docs } entries");
                }
                pageMaps = new List<CommentPageMap>();
                int index = 0;
                foreach (object entry in pagesRaw)
                {
                    pageMaps.Add(new CommentPageMap(string.Format(CultureInfo.InvariantCulture, "{0}: pages[{1}]", name, index), entry as IDictionary));
                    index++;
                }
            }

            if (raw.Contains("exclude") && raw["exclude"] != null)
            {
                if (!(raw["exclude"] is IDictionary excludeRaw))
                {
                    throw new ArgumentException(name + ": exclude must be a map of glob to the reason its files keep their comments");
                }
                excludeMap = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach (DictionaryEntry entry in excludeRaw)
                {
                    string glob = Convert.ToString(entry.Key, CultureInfo.InvariantCulture);
                    string reason = Convert.ToString(entry.Value, CultureInfo.InvariantCulture);
                    if (string.IsNullOrWhiteSpace(reason))
                    {
                        throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: exclude '{1}' needs a reason", name, glob));
                    }
                    excludeMap[glob] = reason.Trim();
                }
            }

            if (raw.Contains("view") && raw["view"] != null)
            {
                string folder = Convert.ToString(raw["view"], CultureInfo.InvariantCulture).Replace('\\', '/');
                if (!folder.StartsWith("out/", StringComparison.Ordinal) || folder.EndsWith("/", StringComparison.Ordinal) || folder.Length == "out/".Length)
                {
                    throw new ArgumentException(string.Format(CultureInfo.InvariantCulture,
                        "{0}: view '{1}' must be a folder under out/, the gitignored output directory", name, raw["view"]));
                }
                view = folder;
            }
        }

        keep = keepLists;
        keep_run = keepRunLists;
        pages = pageMaps;
        exclude = excludeMap;
        foreach (string glob in excludeMap.Keys)
        {
            try
            {
                excludeGlobs.Add(new Catzc.Base.Globs.GlobPattern(glob));
            }
            catch (ArgumentException e)
            {
                throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: exclude '{1}' is not a valid glob: {2}", name, glob, e.Message), e);
            }
        }
    }

    // True when an exclude glob matches the repository-relative, '/'-separated path: the file keeps its comments.
    public bool IsExcluded(string repoRelativePath)
    {
        string path = repoRelativePath?.Replace('\\', '/');
        return !string.IsNullOrEmpty(path) && excludeGlobs.Any(glob => glob.Matches(path));
    }

    // The comment heads that never move in a language's files; empty for a language the config does not name.
    public IReadOnlyList<string> KeepFor(string language) =>
        language != null && keep.TryGetValue(language, out IReadOnlyList<string> heads) ? heads : Array.Empty<string>();

    // True when the trimmed comment line starts with one of the language's kept heads (case-insensitive).
    public bool IsKept(string language, string commentLine)
    {
        string line = commentLine?.Trim() ?? string.Empty;
        return KeepFor(language).Any(head => line.StartsWith(head, StringComparison.OrdinalIgnoreCase));
    }

    // True when the trimmed comment line starts a head whose whole contiguous run stays in the file (the meta head), case-insensitive.
    public bool IsKeptRun(string language, string commentLine)
    {
        string line = commentLine?.Trim() ?? string.Empty;
        return language != null && keep_run.TryGetValue(language, out IReadOnlyList<string> heads)
            && heads.Any(head => line.StartsWith(head, StringComparison.OrdinalIgnoreCase));
    }

    // The comment page of a repository-relative file: the first pages map that covers it, or null when none does.
    public string PageFor(string repoRelativePath) =>
        pages.Select(map => map.PageFor(repoRelativePath)).FirstOrDefault(page => page != null);

    static IReadOnlyList<string> Strings(string name, string key, object value, bool requireAny)
    {
        if (!(value is IList list) || value is string)
        {
            throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: {1} must be a list of strings", name, key));
        }
        var items = new List<string>();
        foreach (object item in list)
        {
            string text = Convert.ToString(item, CultureInfo.InvariantCulture);
            if (string.IsNullOrWhiteSpace(text))
            {
                throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: {1} has an empty entry", name, key));
            }
            items.Add(text);
        }
        if (requireAny && items.Count == 0)
        {
            throw new ArgumentException(string.Format(CultureInfo.InvariantCulture, "{0}: {1} must name at least one entry", name, key));
        }
        return items;
    }
}
