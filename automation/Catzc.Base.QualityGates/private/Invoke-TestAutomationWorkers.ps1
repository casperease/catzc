      ExcludeTag: Tags excluded from every worker's run (from Get-TestExcludeTag).
      IncludeTag: Tags every worker's run is limited to; empty runs every test the other filters keep.
      Verbosity: Pester output verbosity inside each worker.
      Workers: Explicit pool size; 0 sizes automatically — max(1, ProcessorCount / 4), never more than the file count.
      GreedyGroupSize: Greedy files run side by side in groups of this size, one group after another; 0 reads greedy_group_size from test-policy.yml.
      TimeoutSeconds: |-
        Hard ceiling per execution phase; on expiry the pool is killed and the run throws. The entry point's own limit, passed down by
