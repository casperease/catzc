    synopsis: Runs the test files through the parallel worker pool (and the serial phase) and aggregates the rows.
    description: |-
      Test-Automation's execution engine. Runs in the location its test run claimed (Enter-TestRunLocation — a run never
      waits for another: it runs in place when the working folder is free, and in a verified snapshot of it
      when another run holds it; [ADR-AUTO-TEST#32](/docs/adr/automation/test-automation.md#rule-adr-auto-test32)),
      round-robins the parallel files across worker shards
      (generated by New-TestAutomationShardScript) and runs them through the PesterRunner pool — live pooled
      output, at most one shard per worker. Then the greedy phase: each greedy-tagged file becomes its own
      single-file shard, and the shards run through the same pool in groups of greedy_group_size (test-policy.yml,
      default 2; -GreedyGroupSize overrides it), the groups one after another and the files within a group
      side by side, so machine-hungry files overlap only within a group and never the parallel phase. Finally the
      serial-tagged files run in a one-worker phase, alone. Aggregates every shard's rows-shard-<N>.json sidecar in shard order; a worker that exited
      outside {0,1} or never wrote its sidecar crashed before finishing, and the aggregation throws naming
      the shard rather than reporting a partial run as the whole truth.

      In a snapshot run the test files map to the same repository-relative paths inside the snapshot, each
      worker loads the snapshot's own importer (or the test run's entry script with its repository root mapped to
      the snapshot), and the run directory stays in the working folder's out/ — the shard results land home by
      construction, and the rows' File paths map back to working-folder paths before aggregation.
    parameters:
      ParallelFiles: The test files to shard across the pool (may be empty when only tagged files are in scope).
